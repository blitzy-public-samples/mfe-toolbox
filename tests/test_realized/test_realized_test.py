def _run_estimators_smoke(
    price: np.ndarray,
    time: np.ndarray,
    time_type: str,
    sampling_type: str,
    sampling_interval,
    subsamples: int = DEFAULT_SUBSAMPLES,
    include_covariance: bool = True,
) -> dict[str, object]:
    """Execute all estimators for one sampling type/interval combination.

    Returns a dict of results keyed by estimator name.  Exceptions are
    caught and stored as ``Exception`` objects so the caller can decide
    whether to fail or skip.

    Ref: realized_test.m:45-87 — main nested loop body
    """
    results: dict[str, object] = {}

    with warnings.catch_warnings():
        warnings.simplefilter('ignore')

        # --- Realized Variance (Ref: realized_test.m:50-51) ---
        try:
            rv_result = realized_variance(
                price, time, time_type, sampling_type, sampling_interval
            )
            results['rv'] = rv_result
        except Exception as exc:
            results['rv_error'] = exc

        try:
            rv_ss_result = realized_variance(
                price, time, time_type, sampling_type, sampling_interval,
                subsamples=subsamples,
            )
            results['rv_ss'] = rv_ss_result
        except Exception as exc:
            results['rv_ss_error'] = exc

        # --- Realized Semivariance (Ref: realized_test.m:52-53) ---
        try:
            rsv_result = realized_semivariance(
                price, time, time_type, sampling_type, sampling_interval
            )
            results['rsv'] = rsv_result
        except Exception as exc:
            results['rsv_error'] = exc

        try:
            rsv_ss_result = realized_semivariance(
                price, time, time_type, sampling_type, sampling_interval,
                subsamples=subsamples,
            )
            results['rsv_ss'] = rsv_ss_result
        except Exception as exc:
            results['rsv_ss_error'] = exc

        # --- Realized Bipower Variation (Ref: realized_test.m:54-59) ---
        try:
            bv_result = realized_bipower_variation(
                price, time, time_type, sampling_type, sampling_interval
            )
            results['bv'] = bv_result
        except Exception as exc:
            results['bv_error'] = exc

        try:
            bv_ss_result = realized_bipower_variation(
                price, time, time_type, sampling_type, sampling_interval,
                subsamples=subsamples,
            )
            results['bv_ss'] = bv_ss_result
        except Exception as exc:
            results['bv_ss_error'] = exc

        # Ref: realized_test.m:56-59 — loop over skip = 0:1
        for skip_val in [0, 1]:
            try:
                bv_skip = realized_bipower_variation(
                    price, time, time_type, sampling_type, sampling_interval,
                    skip=skip_val,
                )
                results[f'bv_skip{skip_val}'] = bv_skip
            except Exception as exc:
                results[f'bv_skip{skip_val}_error'] = exc

            try:
                bv_skip_ss = realized_bipower_variation(
                    price, time, time_type, sampling_type, sampling_interval,
                    skip=skip_val, subsamples=subsamples,
                )
                results[f'bv_skip{skip_val}_ss'] = bv_skip_ss
            except Exception as exc:
                results[f'bv_skip{skip_val}_ss_error'] = exc

        # --- Realized Quarticity (Ref: realized_test.m:63-76) ---
        # Ref: realized_test.m:63 — default quarticity
        try:
            qt_default = realized_quarticity(
                price, time, time_type, sampling_type, sampling_interval
            )
            results['qt_default'] = qt_default
        except Exception as exc:
            results['qt_default_error'] = exc

        # Ref: realized_test.m:64 — Quadpower
        try:
            qt_qp = realized_quarticity(
                price, time, time_type, sampling_type, sampling_interval,
                quarticity_type='Quadpower',
            )
            results['qt_quadpower'] = qt_qp
        except Exception as exc:
            results['qt_quadpower_error'] = exc

        # Ref: realized_test.m:65 — skip=1
        try:
            qt_s1 = realized_quarticity(
                price, time, time_type, sampling_type, sampling_interval,
                skip=1,
            )
            results['qt_skip1'] = qt_s1
        except Exception as exc:
            results['qt_skip1_error'] = exc

        # Ref: realized_test.m:72-76 — nested loop over skip and QType
        for skip_val in [0, 1]:
            for q_type in [None, 'BNS', 'Tripower', 'Quadpower']:
                # Ref: realized_test.m:73 — MATLAB {[]} means default → 'BNS'
                effective_qtype = q_type if q_type is not None else 'BNS'
                try:
                    realized_quarticity(
                        price, time, time_type, sampling_type,
                        sampling_interval,
                        skip=skip_val,
                        quarticity_type=effective_qtype,
                        subsamples=subsamples,
                    )
                    results[f'qt_{effective_qtype}_skip{skip_val}_ss'] = True
                except Exception as exc:
                    results[f'qt_{effective_qtype}_skip{skip_val}_ss_error'] = exc

        # --- Realized Covariance (Ref: realized_test.m:78-83) ---
        # Ref: realized_test.m:78 — if ~strfind(samplingType,'Bus')
        # Python: covariance excluded when sampling type contains 'Bus'
        if include_covariance:
            # Ref: realized_test.m:79 — single series
            try:
                rc1 = realized_covariance(
                    [price], [time], time_type, sampling_type,
                    sampling_interval,
                )
                results['rc_single'] = rc1
            except Exception as exc:
                results['rc_single_error'] = exc

            # Ref: realized_test.m:80 — single series with subsamples=5
            try:
                rc1_ss = realized_covariance(
                    [price], [time], time_type, sampling_type,
                    sampling_interval, subsamples=5,
                )
                results['rc_single_ss'] = rc1_ss
            except Exception as exc:
                results['rc_single_ss_error'] = exc

            # Ref: realized_test.m:81 — two series
            try:
                rc2 = realized_covariance(
                    [price, price], [time, time], time_type,
                    sampling_type, sampling_interval,
                )
                results['rc_dual'] = rc2
            except Exception as exc:
                results['rc_dual_error'] = exc

            # Ref: realized_test.m:82 — two series with subsamples=5
            try:
                rc2_ss = realized_covariance(
                    [price, price], [time, time], time_type,
                    sampling_type, sampling_interval, subsamples=5,
                )
                results['rc_dual_ss'] = rc2_ss
            except Exception as exc:
                results['rc_dual_ss_error'] = exc

    return results


