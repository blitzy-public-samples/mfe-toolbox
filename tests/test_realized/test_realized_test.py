def _load_fixture(name: str):
    """Load a .npy fixture file from the realized fixtures directory.

    Parameters
    ----------
    name : str
        File name (e.g. ``'realized_test.npy'``).

    Returns
    -------
    np.ndarray or None
        The loaded array, or ``None`` if the file does not exist.
    """
    path = os.path.join(FIXTURE_DIR, name)
    if os.path.exists(path):
        return np.load(path, allow_pickle=True)
    return None


def _load_reference_data() -> dict | None:
    """Load the comprehensive realized_test fixture as a dict.

    The fixture file ``realized_test.npy`` is generated by the Octave/MATLAB
    fixture script and contains structured reference outputs for all
    estimators exercised by realized_test.m.

    Returns
    -------
    dict or None
        Reference data dictionary, or ``None`` if unavailable.
    """
    data = _load_fixture('realized_test.npy')
    if data is None:
        return None
    # The .npy file wraps a 0-d object array containing a dict
    if data.dtype == object:
        return data.item()
    return None


