class TestRealizedTestModule:
    """Test the ``realized_test()`` function as a complete integration test.

    Verifies that the smoke test function from
    ``mfe_toolbox.realized.realized_test`` runs to completion without
    unhandled exceptions.
    """

    def test_smoke_test_runs(self, es_data):
        """The realized_test() function runs without unhandled error.

        This exercises the entire integration test that calls every
        realized estimator with multiple parameter combinations.

        Ref: realized_test.m:1-91 — full script execution
        """
        # The realized_test() function uses try/except internally for
        # individual estimator calls, so only a missing data file will
        # cause it to raise.  The es_data fixture ensures data is available.
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            # realized_test() should complete without raising
            realized_test()

    def test_smoke_test_no_exceptions(self, es_data):
        """No exceptions propagate from realized_test().

        Double-checks that the smoke test does not leak exceptions even
        for edge-case parameter combinations.
        """
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            try:
                realized_test()
                completed = True
            except FileNotFoundError:
                # Data not found — acceptable in CI without fixtures
                pytest.skip('ES_20090817 data not found by realized_test()')
            except Exception as exc:
                completed = False
                pytest.fail(
                    f'realized_test() raised an unexpected exception: {exc}'
                )
            assert completed, 'realized_test() did not complete'


