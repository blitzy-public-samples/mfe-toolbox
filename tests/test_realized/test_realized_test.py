@pytest.fixture
def synthetic_brownian():
    """Generate synthetic geometric Brownian motion data.

    Matches the construction in realized_test.m for testing the quantile
    variance estimator.

    Ref: realized_test.m:15-17
        r = randn(390*300,1)/sqrt(390*300);
        p = cumsum([0;r]);
        p = exp(p);

    Uses ``default_rng(42)`` for reproducibility (MATLAB uses different
    RNG seed — cross-RNG parity is not expected for random data).
    """
    rng = np.random.default_rng(42)
    n = 390 * 300
    # Ref: realized_test.m:15 — r = randn(390*300,1)/sqrt(390*300)
    r = rng.standard_normal(n) / np.sqrt(n)
    # Ref: realized_test.m:16-17 — p=cumsum([0;r]); p=exp(p);
    # MATLAB cumsum([0;r]) prepends 0 before cumulating
    p = np.exp(np.cumsum(np.concatenate([[0.0], r])))
    # Ref: realized_test.m:18 — linspace(0,1,length(p))
    t = np.linspace(0.0, 1.0, n + 1)
    return p, t


