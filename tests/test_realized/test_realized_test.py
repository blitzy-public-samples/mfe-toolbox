class TestRealizedTestSamplingLoop:
    """Reproduce the realized_test.m sampling loop over all 5 types.

    Ref: realized_test.m:33-34, 45-87

    Each test exercises a specific sampling type with its corresponding
    interval values, calling all estimators and verifying no exceptions.
    Where fixture data is available, numerical parity is also checked.
    """

    # ------------------------------------------------------------------
    # Smoke verification helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _verify_finite_positive(results: dict, sampling_type: str,
                                 interval) -> None:
        """Verify all estimator results are finite and positive.

        This is the primary smoke-test assertion for per-type loop tests.
        Strict parity checking is deferred to ``test_full_integration_parity``.
        """
        for key, value in results.items():
            if key.endswith('_error'):
                continue  # errors are checked separately
            if not isinstance(value, tuple):
                continue
            # The first element of every estimator tuple is the primary
            # scalar/array result.
            primary = value[0]
            if isinstance(primary, np.ndarray):
                assert np.all(np.isfinite(primary)), (
                    f'{key} returned non-finite values for '
                    f'{sampling_type}/{interval}'
                )
            elif isinstance(primary, (int, float, np.floating)):
                assert np.isfinite(primary), (
                    f'{key} returned non-finite value ({primary}) for '
                    f'{sampling_type}/{interval}'
                )

    # ------------------------------------------------------------------
    # Helpers for parity checking
    # ------------------------------------------------------------------

    @staticmethod
    def _get_fixture_key(stype: str, interval) -> str:
        """Build the fixture dictionary key prefix.

        Parameters
        ----------
        stype : str
            Sampling type (e.g. 'CalendarTime').
        interval : int or float or np.ndarray
            Sampling interval.  For Fixed type, uses 300 as the key.

        Returns
        -------
        str
            Key prefix, e.g. 'CalendarTime_60'.
        """
        if isinstance(interval, np.ndarray):
            # Fixed sampling — fixture uses the step size (300)
            return f'{stype}_300'
        return f'{stype}_{int(interval)}'

    def _check_rv_parity(
        self, results: dict, ref: dict | None, key_prefix: str
    ) -> None:
        """Check realized variance parity against fixture."""
        if ref is None or 'rv_results' not in ref:
            return
        rv_ref = ref['rv_results']
        rv_key = f'{key_prefix}_rv'
        if rv_key in rv_ref and 'rv' in results:
            rv_tuple = results['rv']
