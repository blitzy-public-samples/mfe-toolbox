# =========================================================================

class TestStationaryBootstrapReproducibility:
    """Reproducibility tests — verify structural consistency across calls."""

    def test_reproducibility_structural(self, sample_data):
        """Two calls with the same data produce structurally valid outputs.

        Since stationary_bootstrap uses an internal unseeded RNG,
        consecutive calls will produce different indices, but both
        outputs must satisfy all structural invariants.
        """
        bsdata1, indices1 = stationary_bootstrap(
            sample_data, B=B_DEFAULT, w=W_DEFAULT
        )
        bsdata2, indices2 = stationary_bootstrap(
            sample_data, B=B_DEFAULT, w=W_DEFAULT
        )

        # Both outputs should be valid
        for bsdata, indices, label in [
            (bsdata1, indices1, "call1"),
            (bsdata2, indices2, "call2"),
        ]:
            assert bsdata.shape == (T_DEFAULT, B_DEFAULT), f"{label}: shape mismatch"
            assert np.all(indices >= 0), f"{label}: negative index"
            assert np.all(indices < T_DEFAULT), f"{label}: index >= T"
            npt.assert_array_equal(
                bsdata, sample_data.ravel()[indices],
                err_msg=f"{label}: data consistency failed"
            )

        # With overwhelming probability, two calls produce different indices
        # (probability of exact match is astronomically small)
        assert not np.array_equal(indices1, indices2), (
            "Two calls with unseeded RNG produced identical indices — "
            "extremely unlikely unless RNG is broken"
        )

    def test_different_data_different_bsdata(self, rng):
        """Different input data produce different bootstrapped values."""
        data1 = rng.standard_normal(50).reshape(-1, 1)
        data2 = rng.standard_normal(50).reshape(-1, 1) + 100.0
        bsdata1, _ = stationary_bootstrap(data1, B=10, w=5)
        bsdata2, _ = stationary_bootstrap(data2, B=10, w=5)
        # bsdata2 values should be shifted by ~100 relative to bsdata1
        assert np.mean(bsdata2) > np.mean(bsdata1) + 50, (
            "bsdata from shifted data should have much higher mean"
        )


