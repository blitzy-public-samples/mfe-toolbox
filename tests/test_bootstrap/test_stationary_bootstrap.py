# Phase 9: Comparison with Block Bootstrap
# =========================================================================

class TestStationaryVsBlockBootstrap:
    """Comparison tests between stationary and block bootstrap.

    Verifies the defining difference: stationary bootstrap produces
    geometrically variable block lengths while block bootstrap uses
    fixed block lengths.
    """

    def test_different_block_length_distributions(self, sample_data):
        """Stationary and block bootstrap produce structurally different
        index patterns — variable vs fixed block lengths.

        The block bootstrap always produces blocks of exactly length w,
        while the stationary bootstrap produces geometric block lengths
        with E[block_length] = w.
        """
        from mfe_toolbox.bootstrap.block_bootstrap import block_bootstrap

        _, stat_indices = stationary_bootstrap(
            sample_data, B=50, w=W_DEFAULT
        )
        _, block_indices = block_bootstrap(
            sample_data, B=50, w=W_DEFAULT
        )

        t = T_DEFAULT
        w = W_DEFAULT

        # Measure block length variability for stationary bootstrap
        stat_block_lengths = []
        for b in range(stat_indices.shape[1]):
            col = stat_indices[:, b]
            current_length = 1
            for i in range(1, len(col)):
                if col[i] == (col[i - 1] + 1) % t:
                    current_length += 1
                else:
                    stat_block_lengths.append(current_length)
                    current_length = 1
            stat_block_lengths.append(current_length)

        # Measure block length variability for block bootstrap
        block_block_lengths = []
        for b in range(block_indices.shape[1]):
            col = block_indices[:, b]
            current_length = 1
            for i in range(1, len(col)):
                if col[i] == (col[i - 1] + 1) % t:
                    current_length += 1
                else:
                    block_block_lengths.append(current_length)
                    current_length = 1
            block_block_lengths.append(current_length)

        stat_std = np.std(stat_block_lengths)
        block_std = np.std(block_block_lengths)

        # Stationary bootstrap should have MUCH higher block-length variability
        # Block bootstrap has fixed blocks of length w (std ≈ 0 for full blocks)
        # Stationary bootstrap has geometric blocks (std = sqrt(w*(w-1)) ≈ w for large w)
        assert stat_std > block_std, (
            f"Stationary block-length std ({stat_std:.2f}) should exceed "
            f"block bootstrap std ({block_std:.2f})"
        )

    def test_both_produce_valid_outputs(self, sample_data):
        """Both bootstrap methods produce valid (T, B) outputs with correct indices."""
        from mfe_toolbox.bootstrap.block_bootstrap import block_bootstrap

        stat_bs, stat_idx = stationary_bootstrap(
            sample_data, B=20, w=W_DEFAULT
        )
        block_bs, block_idx = block_bootstrap(
            sample_data, B=20, w=W_DEFAULT
        )

        for bs, idx, name in [
            (stat_bs, stat_idx, "stationary"),
            (block_bs, block_idx, "block"),
        ]:
            assert bs.shape == (T_DEFAULT, 20), f"{name}: shape mismatch"
            assert idx.shape == (T_DEFAULT, 20), f"{name}: shape mismatch"
            assert np.all(idx >= 0), f"{name}: negative index"
            assert np.all(idx < T_DEFAULT), f"{name}: index >= T"
            npt.assert_array_equal(
                bs, sample_data.ravel()[idx],
                err_msg=f"{name}: data consistency failed"
            )
