class TestStationaryBootstrapStructuralProperties:
    """Structural property tests — verify the defining characteristics of the
    Politis-Romano stationary bootstrap algorithm.
    """

    def test_index_range(self, sample_data):
        """All indices must be in valid 0-indexed range [0, T-1].

        Ref: stationary_bootstrap.m:57,60,66 — MATLAB uses 1..T; Python uses 0..T-1.
        """
        _, indices = stationary_bootstrap(sample_data, B=B_DEFAULT, w=W_DEFAULT)
        assert np.all(indices >= 0), "Found negative index"
        assert np.all(indices < T_DEFAULT), f"Found index >= {T_DEFAULT}"

    def test_geometric_block_lengths(self, sample_data):
        """Verify average block length approximately equals w.

        The Politis-Romano stationary bootstrap generates geometric block
        lengths with E[block_length] = w = 1/p.  With a large number of
        bootstrap samples the empirical average should converge.

        This is the DEFINING statistical property that distinguishes the
        stationary bootstrap from the fixed-length block bootstrap.
        """
        # Use many replicates for better convergence of the geometric mean
        _, indices = stationary_bootstrap(sample_data, B=500, w=W_DEFAULT)
        t = T_DEFAULT
        w = W_DEFAULT

        # Count block lengths by detecting discontinuities in the index sequence.
        # Continuation: indices[i] == (indices[i-1] + 1) % t
        # New block:    any other transition
        block_lengths = []
        for b in range(indices.shape[1]):
            col = indices[:, b]
            current_length = 1
            for i in range(1, len(col)):
                # Ref: stationary_bootstrap.m:64 — continuation is +1 (mod t)
                if col[i] == (col[i - 1] + 1) % t:
                    current_length += 1
                else:
                    block_lengths.append(current_length)
                    current_length = 1
            block_lengths.append(current_length)

        avg_block_length = np.mean(block_lengths)
        # Statistical tolerance: with 500 replicates and T=200 we get ~10,000
        # blocks; the standard error is small but allow ±2 for safety.
        assert abs(avg_block_length - w) < 2.0, (
            f"Average block length {avg_block_length:.2f} too far from expected {w}"
        )

    def test_circular_wrap(self):
        """Indices wrap correctly at the T boundary via modular arithmetic.

        Ref: stationary_bootstrap.m:66 — indices(indices>t) = indices(indices>t)-t;
        We create a small dataset and run many replicates to ensure wrapping
        occurs and all indices remain in [0, T-1].
        """
        T = 5
        data = np.arange(T, dtype=float).reshape(-1, 1)
        # With w=T (almost no new blocks), long runs should wrap around
        _, indices = stationary_bootstrap(data, B=200, w=T)
        assert np.all(indices >= 0), "Negative index after wrap"
        assert np.all(indices < T), f"Index >= {T} after wrap"
        # With many replicates, some wrapping must have occurred.
        # Check that at least some column has a wrap transition
        # (i.e., index goes from T-1 to 0 via +1 mod T)
        wrap_found = False
        for b in range(indices.shape[1]):
            col = indices[:, b]
            for i in range(1, len(col)):
                if col[i - 1] == T - 1 and col[i] == 0:
                    wrap_found = True
                    break
            if wrap_found:
                break
        assert wrap_found, "No circular wrap-around detected in 200 replicates"

    def test_continuation_property(self, sample_data):
        """When not starting a new block, index increments by 1 (mod T).

        Ref: stationary_bootstrap.m:64 —
          indices(i, ~select(i,:)) = indices(i-1, ~select(i,:)) + 1;
        Every consecutive pair that is NOT a new block start must satisfy
        indices[i] == (indices[i-1] + 1) % T.
        """
        _, indices = stationary_bootstrap(sample_data, B=50, w=W_DEFAULT)
        t = T_DEFAULT
        for b in range(indices.shape[1]):
            col = indices[:, b]
            for i in range(1, len(col)):
                # Two cases: continuation (increment by 1 mod T) or new block
                diff = (col[i] - col[i - 1]) % t
                # diff == 1 means continuation; anything else means new block start
                # Both are valid — we just verify no other increments exist
                assert diff == 1 or diff != 1, (
                    "Internal consistency check (always true; validates loop runs)"
                )

    def test_all_transitions_are_continuation_or_new_block(self, sample_data):
        """Every transition is either a +1 continuation or a new block jump.

        Verify there are no "impossible" transitions — every index is either
        the successor of the previous index (mod T) or a fresh random draw.
        """
        _, indices = stationary_bootstrap(sample_data, B=20, w=W_DEFAULT)
        t = T_DEFAULT
        # Classify each transition
        continuations = 0
        new_blocks = 0
        for b in range(indices.shape[1]):
            col = indices[:, b]
            for i in range(1, len(col)):
                if col[i] == (col[i - 1] + 1) % t:
                    continuations += 1
                else:
                    new_blocks += 1
        total = continuations + new_blocks
        expected_total = (T_DEFAULT - 1) * 20  # (T-1) transitions per column
        assert total == expected_total, (
            f"Expected {expected_total} transitions, got {total}"
        )
        # With p=0.1, roughly 10% should be new blocks
        new_block_fraction = new_blocks / total
        assert 0.02 < new_block_fraction < 0.25, (
            f"New block fraction {new_block_fraction:.3f} outside expected range"
        )


