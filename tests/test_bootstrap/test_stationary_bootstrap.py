class TestStationaryBootstrapParity:
    """Numerical parity tests against MATLAB-generated fixture files.

    Since the Python implementation uses an internal unseeded
    np.random.default_rng(), exact numerical parity with MATLAB's RNG is
    not expected.  Instead, these tests verify:
    1. The MATLAB fixture data is self-consistent (bsdata == data[indices])
    2. The Python function produces structurally valid outputs matching
       the MATLAB fixture shapes and statistical properties
    3. Bootstrap mean convergence (law of large numbers)
    """

    @pytest.mark.parity
    @pytest.mark.requires_fixtures
    def test_fixture_self_consistency(self, fixture_dict):
        """Verify MATLAB fixture is internally consistent: bsdata == data[indices-1].

        The fixture .npy file stores MATLAB 1-indexed indices.
        Converting to 0-indexed (indices - 1) and indexing into data
        should reproduce bsdata exactly.
        """
        for tc_prefix in ["tc1", "tc2", "tc3"]:
            data = fixture_dict[f"{tc_prefix}_data"]
            indices_matlab = fixture_dict[f"{tc_prefix}_indices"]
            bsdata_matlab = fixture_dict[f"{tc_prefix}_bsdata"]

            # Convert MATLAB 1-indexed to Python 0-indexed
            indices_0 = (indices_matlab - 1).astype(int)

            # Verify self-consistency
            expected = data[indices_0]
            npt.assert_allclose(
                expected, bsdata_matlab, atol=ATOL, rtol=RTOL,
                err_msg=f"Fixture {tc_prefix}: bsdata != data[indices-1]"
            )

    @pytest.mark.parity
    @pytest.mark.requires_fixtures
    def test_fixture_index_range(self, fixture_dict):
        """Verify MATLAB fixture indices are in valid 1-indexed range [1, T]."""
        for tc_prefix, expected_T in [("tc1", 200), ("tc2", 50), ("tc3", 100)]:
            indices = fixture_dict[f"{tc_prefix}_indices"]
            assert indices.min() >= 1, (
                f"Fixture {tc_prefix}: min index {indices.min()} < 1"
            )
            assert indices.max() <= expected_T, (
                f"Fixture {tc_prefix}: max index {indices.max()} > {expected_T}"
            )

    @pytest.mark.parity
    @pytest.mark.requires_fixtures
    def test_fixture_shapes(self, fixture_dict):
        """Verify MATLAB fixture output shapes match expected dimensions."""
        expected = {
            "tc1": (200, 100),
            "tc2": (50, 10),
            "tc3": (100, 50),
        }
        for tc_prefix, (T, B) in expected.items():
            bsdata = fixture_dict[f"{tc_prefix}_bsdata"]
            indices = fixture_dict[f"{tc_prefix}_indices"]
            assert bsdata.shape == (T, B), (
                f"Fixture {tc_prefix}: bsdata shape {bsdata.shape} != ({T}, {B})"
            )
            assert indices.shape == (T, B), (
                f"Fixture {tc_prefix}: indices shape {indices.shape} != ({T}, {B})"
            )

    @pytest.mark.parity
    @pytest.mark.requires_fixtures
    def test_fixture_geometric_block_property(self, fixture_dict):
        """Verify MATLAB fixture indices exhibit geometric block-length distribution.

        The Politis-Romano stationary bootstrap has E[block_length] = w.
        The MATLAB fixture should display this property.
        """
        for tc_prefix, expected_w in [("tc1", 10), ("tc2", 5), ("tc3", 20)]:
            indices = fixture_dict[f"{tc_prefix}_indices"]
            T = int(fixture_dict[f"{tc_prefix}_data"].shape[0])

            # Convert MATLAB 1-indexed to 0-indexed for modular arithmetic
            idx = (indices - 1).astype(int)

            block_lengths = []
            for b in range(idx.shape[1]):
                col = idx[:, b]
                current_length = 1
                for i in range(1, len(col)):
                    if col[i] == (col[i - 1] + 1) % T:
                        current_length += 1
                    else:
                        block_lengths.append(current_length)
                        current_length = 1
                block_lengths.append(current_length)

            avg_block = np.mean(block_lengths)
            # Allow generous tolerance for fixture block lengths
            assert abs(avg_block - expected_w) < expected_w * 0.5, (
                f"Fixture {tc_prefix}: avg block {avg_block:.2f} "
                f"far from expected w={expected_w}"
            )

    @pytest.mark.parity
    @pytest.mark.requires_fixtures
    def test_separate_fixture_self_consistency(
        self, fixture_sb_data, fixture_sb_indices, fixture_sb_bsdata
    ):
        """Verify separate fixture files are self-consistent.

        stationary_bootstrap_sb_bsdata == sb_data[sb_indices - 1]
        (MATLAB 1-indexed indices)
        """
        indices_0 = (fixture_sb_indices - 1).astype(int)
        expected = fixture_sb_data[indices_0]
        npt.assert_allclose(
            expected, fixture_sb_bsdata, atol=ATOL, rtol=RTOL,
            err_msg="Separate sb fixture: bsdata != data[indices-1]"
        )

    @pytest.mark.parity
    @pytest.mark.requires_fixtures
    def test_python_output_matches_fixture_structure(self, fixture_dict):
        """Run Python stationary_bootstrap on fixture data and verify structural match.

        Since RNGs differ between MATLAB and Python, we cannot expect exact
        index parity.  Instead we verify the Python output has the same shape,
        valid index range, and consistent data reconstruction.
        """
        for tc_prefix in ["tc1", "tc2", "tc3"]:
            data = fixture_dict[f"{tc_prefix}_data"].reshape(-1, 1)
            B = int(fixture_dict[f"{tc_prefix}_B"])
            w = int(fixture_dict[f"{tc_prefix}_w"])
            T = data.shape[0]

            bsdata, indices = stationary_bootstrap(data, B=B, w=w)

            assert bsdata.shape == (T, B), (
                f"{tc_prefix}: bsdata shape mismatch"
            )
            assert indices.shape == (T, B), (
                f"{tc_prefix}: indices shape mismatch"
            )
            assert np.all(indices >= 0) and np.all(indices < T), (
                f"{tc_prefix}: indices out of range"
            )
            npt.assert_array_equal(
                bsdata, data.ravel()[indices],
                err_msg=f"{tc_prefix}: bsdata != data[indices]"
            )

    @pytest.mark.parity
    def test_bootstrap_mean_convergence(self, sample_data):
        """Bootstrap sample means converge to the original sample mean.

        By the law of large numbers, the mean of bootstrap means should
        approximate the population (sample) mean as B grows.
        """
        bsdata, _ = stationary_bootstrap(sample_data, B=1000, w=W_DEFAULT)
        sample_mean = np.mean(sample_data)
        bootstrap_means = np.mean(bsdata, axis=0)  # mean of each replicate
        grand_mean = np.mean(bootstrap_means)
        # With B=1000 replicates, the bootstrap grand mean should be close
        assert abs(grand_mean - sample_mean) < 0.15, (
            f"Bootstrap grand mean {grand_mean:.4f} too far from "
            f"sample mean {sample_mean:.4f}"
        )


