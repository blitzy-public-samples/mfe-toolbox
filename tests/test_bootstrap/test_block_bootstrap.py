class TestBlockBootstrapStatisticalProperties:
    """Statistical property tests verifying bootstrap distributional correctness."""

    def test_bootstrap_mean_close_to_data_mean(self, sample_data):
        """Grand mean of bootstrap means ≈ original sample mean.

        The block bootstrap preserves the unconditional mean: E[X*] = Xbar.
        With B=500, the grand mean should be close to the data mean.
        """
        bsdata, _ = block_bootstrap(sample_data, B=500, w=W_DEFAULT)
        original_mean = np.mean(sample_data)
        bootstrap_means = np.mean(bsdata, axis=0)
        grand_mean = np.mean(bootstrap_means)
        # Grand mean should be close — generous tolerance for randomness
        assert abs(grand_mean - original_mean) < 0.5, (
            f"Bootstrap grand mean {grand_mean:.6f} too far from "
            f"data mean {original_mean:.6f}"
        )

    def test_bootstrap_variance_reasonable(self, sample_data):
        """Bootstrap sample variances should be in a reasonable range.

        Each bootstrap column's variance should not be dramatically different
        from the original data variance.
        """
        bsdata, _ = block_bootstrap(sample_data, B=100, w=W_DEFAULT)
        data_var = np.var(sample_data)
        bootstrap_vars = np.var(bsdata, axis=0)
        mean_bs_var = np.mean(bootstrap_vars)
        # Bootstrap variance should be within a factor of 3 of data variance
        assert mean_bs_var > data_var / 3, (
            f"Bootstrap var {mean_bs_var:.6f} too small vs data var {data_var:.6f}"
        )
        assert mean_bs_var < data_var * 3, (
            f"Bootstrap var {mean_bs_var:.6f} too large vs data var {data_var:.6f}"
        )

    def test_bootstrap_all_data_points_sampled(self, sample_data):
        """With enough bootstrap samples, every data point should appear.

        With B=500 and T=200, every observation should be sampled at least once.
        """
        _, indices = block_bootstrap(sample_data, B=500, w=W_DEFAULT)
        unique_indices = np.unique(indices)
        assert len(unique_indices) == T_DEFAULT, (
            f"Only {len(unique_indices)}/{T_DEFAULT} unique indices sampled"
        )

    def test_bootstrap_columns_independent(self, sample_data):
        """Different bootstrap columns should not be identical.

        With B=100, no two columns should have the same indices.
        """
        _, indices = block_bootstrap(sample_data, B=100, w=W_DEFAULT)
        for i in range(min(99, indices.shape[1] - 1)):
            assert not np.array_equal(indices[:, i], indices[:, i + 1]), (
                f"Columns {i} and {i+1} are identical"
            )


