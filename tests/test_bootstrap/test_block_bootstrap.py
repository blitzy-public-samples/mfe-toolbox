class TestBlockBootstrapInputValidation:
    """Input validation tests — verify errors match MATLAB block_bootstrap.m."""

    def test_data_not_column(self, rng):
        """Pass a T×2 matrix — expect ValueError about column vector.

        Ref: block_bootstrap.m:35-36 — if k>1 error('DATA must be a column vector')
        """
        data = rng.standard_normal((100, 2))
        with pytest.raises(ValueError, match="DATA must be a column vector"):
            block_bootstrap(data, B=10, w=5)

    def test_data_too_short_single_element(self):
        """Pass data with T=1 — expect ValueError about minimum observations.

        Ref: block_bootstrap.m:38-39 — if t<2 error('DATA must have at least 2 observations.')
        """
        data = np.array([5.0]).reshape(-1, 1)
        with pytest.raises(ValueError, match="DATA must have at least 2 observations"):
            block_bootstrap(data, B=5, w=1)

    def test_data_too_short_empty(self):
        """Pass empty data — expect ValueError about minimum observations."""
        data = np.array([]).reshape(-1, 1)
        with pytest.raises(ValueError, match="DATA must have at least 2 observations"):
            block_bootstrap(data, B=5, w=1)

    def test_w_greater_than_t(self):
        """Pass w > T — expect ValueError about w range.

        Ref: block_bootstrap.m:41-42 — w>t triggers error
        """
        data = np.arange(10, dtype=float).reshape(-1, 1)
        with pytest.raises(ValueError, match="W must be a positive scalar integer smaller than T"):
            block_bootstrap(data, B=5, w=11)

    def test_w_zero(self):
        """Pass w=0 — expect ValueError.

        Ref: block_bootstrap.m:41-42 — w<1 triggers error
        """
        data = np.arange(10, dtype=float).reshape(-1, 1)
        with pytest.raises(ValueError, match="W must be a positive scalar integer smaller than T"):
            block_bootstrap(data, B=5, w=0)

    def test_w_negative(self):
        """Pass w=-1 — expect ValueError."""
        data = np.arange(10, dtype=float).reshape(-1, 1)
        with pytest.raises(ValueError, match="W must be a positive scalar integer smaller than T"):
            block_bootstrap(data, B=5, w=-1)

    def test_w_non_integer(self):
        """Pass w=1.5 — expect ValueError because floor(w)!=w.

        Ref: block_bootstrap.m:41 — floor(w)~=w triggers error
        """
        data = np.arange(10, dtype=float).reshape(-1, 1)
        with pytest.raises(ValueError, match="W must be a positive scalar integer smaller than T"):
            block_bootstrap(data, B=5, w=1.5)

    def test_B_zero(self):
        """Pass B=0 — expect ValueError about B.

        Ref: block_bootstrap.m:44-45 — B<1 triggers error
        """
        data = np.arange(10, dtype=float).reshape(-1, 1)
        with pytest.raises(ValueError, match="B must be a positive scalar integer"):
            block_bootstrap(data, B=0, w=2)

    def test_B_negative(self):
        """Pass B=-1 — expect ValueError."""
        data = np.arange(10, dtype=float).reshape(-1, 1)
        with pytest.raises(ValueError, match="B must be a positive scalar integer"):
            block_bootstrap(data, B=-1, w=2)

    def test_B_non_integer(self):
        """Pass B=2.5 — expect ValueError because floor(B)!=B."""
        data = np.arange(10, dtype=float).reshape(-1, 1)
        with pytest.raises(ValueError, match="B must be a positive scalar integer"):
            block_bootstrap(data, B=2.5, w=2)

    def test_data_3d_array(self):
        """Pass 3-D array — after reshape/validation should raise ValueError."""
