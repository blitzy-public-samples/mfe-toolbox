class TestBlockBootstrapStructure:
    """Block structure, index range, and circular wrap-around tests."""

    def test_index_range(self, sample_data):
        """All indices in valid range [0, T-1].

        Ref: block_bootstrap.m:64 — indices(indices>t) = indices(indices>t)-t
        ensures all indices are in [1, t] (MATLAB) / [0, t-1] (Python).
        """
        _, indices = block_bootstrap(sample_data, B=B_DEFAULT, w=W_DEFAULT)
        assert np.all(indices >= 0), (
            f"Found indices below 0: min={indices.min()}"
        )
        assert np.all(indices < T_DEFAULT), (
            f"Found indices >= T={T_DEFAULT}: max={indices.max()}"
        )

    def test_block_structure_consecutive_diffs(self, sample_data):
        """Within each block of w rows, consecutive indices differ by 1 (mod T).

        This is the DEFINING property of block bootstrap — consecutive indices
        within blocks must be sequential with circular wrap-around.

        Ref: block_bootstrap.m:58-62 — adder=(0:w-1)' produces consecutive offsets
        """
        _, indices = block_bootstrap(sample_data, B=B_DEFAULT, w=W_DEFAULT)
        w = W_DEFAULT
        t = T_DEFAULT
        # Check all bootstrap columns (not just a few) for comprehensive coverage
        for b in range(min(B_DEFAULT, 10)):
            for block_idx in range(t // w):
                row_start = block_idx * w
                block = indices[row_start:row_start + w, b]
                if len(block) < 2:
                    continue
                # Compute forward differences modulo T
                # Ref: block_bootstrap.m:64 — circular wrapping means
                # diff can be 1 or -(T-1); both are equivalent to +1 mod T
                diffs = np.diff(block) % t
                assert np.all(diffs == 1), (
                    f"Block structure violated: col {b}, block starting at row "
                    f"{row_start}, diffs (mod {t}) = {diffs}"
                )

    def test_circular_wrap_indices_valid(self, sample_data):
        """Using w=T forces wrapping for most start positions.

        All indices must remain in [0, T-1] even with maximum block length.
        """
        bsdata, indices = block_bootstrap(sample_data, B=10, w=T_DEFAULT)
        assert np.all(indices >= 0), f"min index = {indices.min()}"
        assert np.all(indices < T_DEFAULT), f"max index = {indices.max()}"

    def test_circular_wrap_block_continuity(self):
        """Verify circular continuity: block crossing T boundary wraps correctly.

        With T=10, w=10, blocks must wrap around: e.g. start=8 → [8,9,0,1,...,7].
        """
        data = np.arange(10, dtype=float).reshape(-1, 1)
        _, indices = block_bootstrap(data, B=50, w=10)
        t = 10
        # Each column is one block of length 10 starting from random position
        for b in range(50):
            col = indices[:, b]
            diffs = np.diff(col) % t
            assert np.all(diffs == 1), (
                f"Circular wrap failed in col {b}: diffs (mod {t}) = {diffs}"
            )

    def test_number_of_blocks_exact_fit(self):
        """T=200, w=10 → s=20 blocks, exact fit (no truncation needed).

        Ref: block_bootstrap.m:52 — s=ceil(t/w)
        """
        data = np.arange(200, dtype=float).reshape(-1, 1)
        bsdata, indices = block_bootstrap(data, B=5, w=10)
        assert bsdata.shape == (200, 5)
        assert indices.shape == (200, 5)

    def test_number_of_blocks_with_truncation(self):
        """T=205, w=10 → s=21 blocks, last block truncated to 5 rows.

        Ref: block_bootstrap.m:63 — indices=indices(1:t,:) truncation
        """
        t_val = 205
        data = np.arange(t_val, dtype=float).reshape(-1, 1)
        bsdata, indices = block_bootstrap(data, B=5, w=10)
        assert bsdata.shape == (t_val, 5), f"shape {bsdata.shape}"
        assert indices.shape == (t_val, 5), f"shape {indices.shape}"
        # All indices should still be in range
        assert np.all(indices >= 0)
        assert np.all(indices < t_val)

    def test_number_of_blocks_large_w(self):
        """T=100, w=25 → s=4 blocks, exact fit.

        Tests the fixture tc3 case dimensions.
        """
        data = np.arange(100, dtype=float).reshape(-1, 1)
        bsdata, indices = block_bootstrap(data, B=3, w=25)
        assert bsdata.shape == (100, 3)
        assert indices.shape == (100, 3)


