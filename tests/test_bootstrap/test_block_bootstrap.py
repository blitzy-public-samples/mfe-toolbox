class TestBlockBootstrapFunctional:
    """Functional tests covering edge cases and special configurations."""

    def test_w_equals_1_iid_bootstrap(self):
        """w=1 gives independent (IID) bootstrap — each index drawn independently.

        With w=1, s=T blocks of size 1. No block structure.
        """
        data = np.arange(50, dtype=float).reshape(-1, 1)
        _, indices = block_bootstrap(data, B=20, w=1)
        assert indices.shape == (50, 20)
        assert np.all(indices >= 0)
        assert np.all(indices < 50)
        # With w=1, every row is an independent draw from [0, T-1]
        # So not all values in a column should be the same (statistically)
        # Check at least some variability exists
        assert np.any(np.diff(indices, axis=0) != 0), (
            "With w=1, indices should show variability across rows"
        )

    def test_w_equals_t_single_block(self):
        """w=T gives one block per bootstrap sample — entire data is one block.

        Each column should be a contiguous (circularly-wrapped) sequence of
        length T starting at a random position.
        """
        t_val = 20
        data = np.arange(t_val, dtype=float).reshape(-1, 1)
        _, indices = block_bootstrap(data, B=10, w=t_val)
        assert indices.shape == (t_val, 10)
        # Each column must be a single contiguous block of length T
        for b in range(10):
            col = indices[:, b]
            diffs = np.diff(col) % t_val
            assert np.all(diffs == 1), (
                f"w=T block not contiguous in col {b}: diffs={diffs}"
            )

    def test_1d_input_accepted(self):
        """Accept 1-D array — auto-reshaped to column vector internally.

        Ref: block_bootstrap.py:124 — if data.ndim == 1: data = data.reshape(-1, 1)
        """
        data = np.arange(50, dtype=float)  # 1-D array, no reshape
        bsdata, indices = block_bootstrap(data, B=5, w=5)
        assert bsdata.shape[0] == 50, f"bsdata rows={bsdata.shape[0]} != 50"
        assert indices.shape[0] == 50, f"indices rows={indices.shape[0]} != 50"
        assert bsdata.shape[1] == 5
        assert indices.shape[1] == 5

    def test_index_only_mode(self, index_data):
        """Pass data=arange(T) to get index-only bootstrap.

        When data is arange(T), bsdata[i,j] = data[indices[i,j]] = indices[i,j].
        So bsdata should equal indices cast to float.
        Ref: block_bootstrap.m:17-18 COMMENTS section
        """
        bsdata, indices = block_bootstrap(index_data, B=B_DEFAULT, w=W_DEFAULT)
        npt.assert_array_equal(
            bsdata, indices.astype(float),
            err_msg="Index-only mode: bsdata should equal indices as float",
        )

    def test_B_equals_1(self):
        """Single bootstrap replicate — B=1."""
        data = np.arange(50, dtype=float).reshape(-1, 1)
        bsdata, indices = block_bootstrap(data, B=1, w=5)
        assert bsdata.shape == (50, 1)
        assert indices.shape == (50, 1)
        # Verify block structure in single column
        for block_start in range(0, 50, 5):
            block = indices[block_start:block_start + 5, 0]
            diffs = np.diff(block) % 50
            assert np.all(diffs == 1)

    def test_different_B_values(self):
        """Test with varying B values: B=1, B=50, B=500."""
        data = np.arange(50, dtype=float).reshape(-1, 1)
        for b_val in [1, 50, 500]:
            bsdata, indices = block_bootstrap(data, B=b_val, w=5)
            assert bsdata.shape == (50, b_val), (
                f"B={b_val}: bsdata shape {bsdata.shape} != (50, {b_val})"
            )
            assert indices.shape == (50, b_val)
            assert np.all(indices >= 0)
            assert np.all(indices < 50)

    def test_small_data(self, small_data):
        """Minimal case: T=5, w=2, B=3.

        s = ceil(5/2) = 3 blocks → 3*2 = 6 rows, truncated to 5.
        """
        bsdata, indices = block_bootstrap(small_data, B=3, w=2)
        assert bsdata.shape == (5, 3)
        assert indices.shape == (5, 3)
        assert np.all(indices >= 0)
        assert np.all(indices < 5)
        # Check data consistency
        npt.assert_array_equal(bsdata, small_data.ravel()[indices])

    def test_w_equals_t_minus_1(self):
        """Edge case: w=T-1 — blocks nearly the entire series."""
        t_val = 10
        data = np.arange(t_val, dtype=float).reshape(-1, 1)
        bsdata, indices = block_bootstrap(data, B=5, w=t_val - 1)
        assert bsdata.shape == (t_val, 5)
        assert indices.shape == (t_val, 5)
        assert np.all(indices >= 0)
        assert np.all(indices < t_val)

    def test_data_values_preserved(self, sample_data):
        """All values in bsdata must come from original data."""
        bsdata, _ = block_bootstrap(sample_data, B=B_DEFAULT, w=W_DEFAULT)
        data_set = set(sample_data.ravel())
        bsdata_set = set(bsdata.ravel())
        assert bsdata_set.issubset(data_set), (
            "bsdata contains values not in original data"
        )

    def test_w_integer_float_accepted(self):
        """w=10.0 (float that equals integer) should be accepted.

        Ref: block_bootstrap.m:41 — floor(w)~=w check; 10.0 passes
        """
        data = np.arange(50, dtype=float).reshape(-1, 1)
        bsdata, indices = block_bootstrap(data, B=5, w=10.0)
        assert bsdata.shape == (50, 5)
        assert indices.shape == (50, 5)

    def test_B_integer_float_accepted(self):
        """B=10.0 (float that equals integer) should be accepted."""
        data = np.arange(50, dtype=float).reshape(-1, 1)
        bsdata, indices = block_bootstrap(data, B=10.0, w=5)
        assert bsdata.shape == (50, 10)
        assert indices.shape == (50, 10)


