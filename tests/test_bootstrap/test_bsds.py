class TestBsdsOutput:
    """Tests verifying return type, count, and value range of bsds outputs."""

    def test_bsds_returns_three_values(self, loss_data):
        """bsds must return exactly 3 values (c, u, l)."""
        bench, models = loss_data
        result = bsds(bench, models, B=50, w=5)
        assert isinstance(result, tuple), "bsds must return a tuple"
        assert len(result) == 3, "bsds must return exactly 3 values"

    def test_bsds_returns_float_scalars(self, loss_data):
        """All three returned values must be Python float scalars."""
        bench, models = loss_data
        c, u, l = bsds(bench, models, B=50, w=5)
        assert isinstance(c, float), f"c must be float, got {type(c)}"
        assert isinstance(u, float), f"u must be float, got {type(u)}"
        assert isinstance(l, float), f"l must be float, got {type(l)}"

    def test_bsds_pvalues_in_valid_range(self, loss_data):
        """All 3 p-values must lie in [0, 1]."""
        bench, models = loss_data
        c, u, l = bsds(bench, models, B=100, w=10)
        assert 0.0 <= c <= 1.0, f"Consistent p-value {c} out of range [0, 1]"
        assert 0.0 <= u <= 1.0, f"Upper p-value {u} out of range [0, 1]"
        assert 0.0 <= l <= 1.0, f"Lower p-value {l} out of range [0, 1]"

    def test_bsds_pvalue_ordering(self, loss_data):
        """Hansen's SPA theory implies l <= c <= u.

        The lower p-value (l) treats all models worse than the benchmark as
        irrelevant; the consistent (c) uses a data-driven threshold; the
        upper (u, White's RC) re-centres at the sample mean.  Hence the
        ordering l <= c <= u should hold in general.
        """
        bench, models = loss_data
        c, u, l = bsds(bench, models, B=200, w=10)
        assert l <= c + 1e-10, (
            f"Lower p-value {l} should be <= consistent p-value {c}"
        )
        assert c <= u + 1e-10, (
            f"Consistent p-value {c} should be <= upper p-value {u}"
        )

    def test_bsds_pvalues_valid_range_block(self, loss_data):
        """p-values must be in [0, 1] when using BLOCK bootstrap."""
        bench, models = loss_data
        c, u, l = bsds(bench, models, B=100, w=10, boot="BLOCK")
        assert 0.0 <= c <= 1.0
        assert 0.0 <= u <= 1.0
        assert 0.0 <= l <= 1.0


