class TestBsdsParity:
    """Parity tests loading MATLAB-generated fixture data.

    Note on stochasticity:
    ----------------------
    Bootstrap p-values depend on random resampling indices generated inside
    ``block_bootstrap`` / ``stationary_bootstrap``.  These functions create
    their own unseeded ``np.random.default_rng()``, so each call to ``bsds``
    produces different p-values.  Exact numerical parity with MATLAB fixtures
    (which used MATLAB's own RNG) is therefore not achievable.

    The parity tests below verify:
    1. The function executes without error on the MATLAB fixture inputs.
    2. Returned p-values lie in [0, 1].
    3. The p-value ordering l <= c <= u holds.
    4. (Soft check) p-values are within a wider tolerance
       (BOOTSTRAP_PVAL_ATOL) of the MATLAB reference values.
    """

    @pytest.mark.parity
    @pytest.mark.requires_fixtures
    def test_bsds_parity_npy_tc1_stationary_studentized(
        self, bootstrap_fixture_dir
    ):
        """Verify behaviour against MATLAB tc1: STUDENTIZED + STATIONARY.

        Fixture: bsds.npy -> tc1 (T=1000, K=10, B=1000, w=12)
        MATLAB results: c=0.812, u=0.812, l=0.58
        """
        fixture_path = bootstrap_fixture_dir / "bsds.npy"
        if not fixture_path.exists():
            pytest.skip("Fixture file not found: bsds.npy")

        fixture = np.load(fixture_path, allow_pickle=True).item()
        bench = fixture["tc1_bench"]
        models = fixture["tc1_models"]
        expected_c = fixture["tc1_c"]
        expected_u = fixture["tc1_u"]
        expected_l = fixture["tc1_l"]
        B = int(fixture["tc1_B"])
        w = int(fixture["tc1_w"])

        c, u, l = bsds(bench, models, B=B, w=w,
                        type_="STUDENTIZED", boot="STATIONARY")

        # Hard checks: p-values must be valid
        assert 0.0 <= c <= 1.0, f"c={c} out of range"
        assert 0.0 <= u <= 1.0, f"u={u} out of range"
        assert 0.0 <= l <= 1.0, f"l={l} out of range"
        assert l <= c + 1e-10, f"l={l} should be <= c={c}"
        assert c <= u + 1e-10, f"c={c} should be <= u={u}"

        # Soft parity check with wider tolerance for stochastic bootstrap.
        # Bootstrap p-values have inherent Monte Carlo variance; exact
        # reproduction requires identical random-number streams.
        npt.assert_allclose(
            c, expected_c, atol=BOOTSTRAP_PVAL_ATOL,
            err_msg="Consistent p-val soft parity (tc1)",
        )
        npt.assert_allclose(
            u, expected_u, atol=BOOTSTRAP_PVAL_ATOL,
            err_msg="Upper p-val soft parity (tc1)",
        )
        npt.assert_allclose(
            l, expected_l, atol=BOOTSTRAP_PVAL_ATOL,
            err_msg="Lower p-val soft parity (tc1)",
        )

