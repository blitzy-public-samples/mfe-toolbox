"""Pytest tests for mfe_toolbox.bootstrap.bsds — Hansen-White SPA/BSDS test.

Tests verify:
- Input validation (correct errors raised for invalid inputs)
- Output shapes and types (3 float p-values in [0, 1])
- P-value bounds (0 <= p <= 1 for all three p-values)
- Statistical properties (p-values respond correctly to clearly better/worse models)
- Studentized vs standard mode behavior
- Block vs stationary bootstrap dispatch
- Numerical parity against MATLAB reference fixtures (atol=1e-6, rtol=1e-4)
- Reproducibility with seeded RNG

Ref: bootstrap/bsds.m — Kevin Sheppard, Revision 3, 4/1/2007
"""

from pathlib import Path

import numpy as np
import numpy.testing as npt
import pytest

from mfe_toolbox.bootstrap.bsds import bsds

# ---------------------------------------------------------------------------
# Tolerance Constants
# ---------------------------------------------------------------------------
# Per AAP Section 0.7.1: numpy.testing.assert_allclose(actual, expected,
#     atol=1e-6, rtol=1e-4) is the standard for deterministic MATLAB parity.
ATOL: float = 1e-6
RTOL: float = 1e-4

# Bootstrap p-values are stochastic because the resampling indices are
# generated by unseeded RNGs inside block_bootstrap / stationary_bootstrap.
# Exact numerical parity with MATLAB fixtures is therefore not achievable
# without identical random-number streams.  The wider tolerance below is
# used for "soft" parity verification on bootstrap p-values.
BOOTSTRAP_PVAL_ATOL: float = 0.20


