class TestBsdsEdgeCases:
    """Edge case tests for bsds boundary conditions."""

    def test_bsds_large_w_relative_to_T(self, rng_local):
        """w close to T (T=50, w=25) should still produce valid results."""
        T = 50
        K = 3
        bench = rng_local.standard_normal(T) ** 2
        models = rng_local.standard_normal((T, K)) ** 2
        c, u, l = bsds(bench, models, B=50, w=25)
        assert 0.0 <= c <= 1.0, f"c={c} out of range"
        assert 0.0 <= u <= 1.0, f"u={u} out of range"
        assert 0.0 <= l <= 1.0, f"l={l} out of range"

    def test_bsds_w_equals_1(self, rng_local):
        """w=1 (independent bootstrap, degenerate blocks) should work.

        With block length 1, the block bootstrap degenerates to an i.i.d.
        bootstrap.
        """
        T = 100
        K = 3
        bench = rng_local.standard_normal(T) ** 2
        models = rng_local.standard_normal((T, K)) ** 2
        c, u, l = bsds(bench, models, B=50, w=1)
        assert 0.0 <= c <= 1.0
        assert 0.0 <= u <= 1.0
        assert 0.0 <= l <= 1.0

    def test_bsds_many_models(self, rng_local):
        """K=50 models (stress test for variance computation)."""
        T = 100
        K = 50
        bench = rng_local.standard_normal(T) ** 2
        models = rng_local.standard_normal((T, K)) ** 2
        c, u, l = bsds(bench, models, B=50, w=5)
        assert 0.0 <= c <= 1.0
        assert 0.0 <= u <= 1.0
        assert 0.0 <= l <= 1.0

    def test_bsds_identical_losses(self, rng_local):
        """When bench == models[:, 0] (zero differential for one model).

        Having one model with identical losses to the benchmark should still
        produce valid p-values.
        """
        T = 100
        K = 3
        bench = rng_local.standard_normal(T) ** 2
        models = rng_local.standard_normal((T, K)) ** 2
        # Make first model identical to benchmark
        models[:, 0] = bench.copy()
        c, u, l = bsds(bench, models, B=50, w=5)
        assert 0.0 <= c <= 1.0
        assert 0.0 <= u <= 1.0
        assert 0.0 <= l <= 1.0

    def test_bsds_B_equals_1(self, rng_local):
        """B=1 (single bootstrap replication) should not crash.

        With only one replication the p-values will be 0.0 or 1.0.
        """
        T = 50
        K = 2
        bench = rng_local.standard_normal(T) ** 2
        models = rng_local.standard_normal((T, K)) ** 2
        c, u, l = bsds(bench, models, B=1, w=5)
        assert c in (0.0, 1.0), f"With B=1, c should be 0 or 1, got {c}"
        assert u in (0.0, 1.0), f"With B=1, u should be 0 or 1, got {u}"
        assert l in (0.0, 1.0), f"With B=1, l should be 0 or 1, got {l}"

    def test_bsds_minimum_valid_inputs(self, rng_local):
        """Minimum valid inputs: T=2, K=1, B=1, w=1."""
        bench = rng_local.standard_normal(2) ** 2
