# Test 7: Non-numeric input raises
# ---------------------------------------------------------------------------
def test_x2mdate_non_numeric_raises() -> None:
    """Verify string input raises ValueError.

    Ref: x2mdate.m:44-46 — if any(ischar(xlsdate)) error('XLSDATE must be numeric')
    """
    with pytest.raises(ValueError, match="XLSDATE must be numeric"):
        x2mdate("not_a_number")

    # Also test with a non-numeric numpy array
    with pytest.raises(ValueError, match="XLSDATE must be numeric"):
        x2mdate(np.array(["a", "b", "c"]))


# ---------------------------------------------------------------------------
# Test 8: Invalid type raises
# ---------------------------------------------------------------------------
def test_x2mdate_invalid_type_raises() -> None:
    """Verify invalid date_type values raise ValueError.

    Ref: x2mdate.m:64-66 — if any(~ismember(type,[0 1]))
        error('TYPE must be either 0 or 1.')
    """
    with pytest.raises(ValueError, match="TYPE must be either 0 or 1"):
        x2mdate(np.array([35000]), date_type=2)

    with pytest.raises(ValueError, match="TYPE must be either 0 or 1"):
        x2mdate(np.array([35000]), date_type=-1)

    with pytest.raises(ValueError, match="TYPE must be either 0 or 1"):
        x2mdate(np.array([35000]), date_type=3)


# ---------------------------------------------------------------------------
# Test 9: Output type verification
# ---------------------------------------------------------------------------
def test_x2mdate_output_type() -> None:
    """Verify x2mdate returns np.ndarray containing pd.Timestamp objects.

    Ref: x2mdate.py docstring — Returns numpy.ndarray of pd.Timestamp
    objects with dtype=object, same shape as input.
    """
    # Array input
    xl_dates = np.array([35000, 40000])
    result = x2mdate(xl_dates)
    assert isinstance(result, np.ndarray), (
        f"Expected np.ndarray, got {type(result)}"
    )
    assert result.dtype == object, (
        f"Expected object dtype for Timestamp array, got {result.dtype}"
    )
    for elem in result.flat:
        assert isinstance(elem, pd.Timestamp), (
            f"Expected pd.Timestamp element, got {type(elem)}"
        )

    # Scalar input → 0-d ndarray
    result_scalar = x2mdate(35000)
    assert isinstance(result_scalar, np.ndarray), (
        f"Scalar input should return np.ndarray, got {type(result_scalar)}"
    )
    assert isinstance(result_scalar.flat[0], pd.Timestamp)


# ---------------------------------------------------------------------------
# Test 10: Fixture parity
# ---------------------------------------------------------------------------
def test_x2mdate_fixture_parity(utility_fixture_dir) -> None:
    """Compare x2mdate output against MATLAB/Octave-generated fixture data.

    Loads the comprehensive fixture from tests/fixtures/utility/x2mdate.npy
    which contains Excel dates, expected MATLAB datenums, and date strings
    for both the 1900 (type=0) and 1904 (type=1) date systems.

    Validates:
    1. Type 0 dates match fixture date_strings_1900
    2. Type 1 dates match fixture date_strings_1904
    3. Mixed-type vector test from fixture
    4. Numerical consistency of MATLAB datenum offsets
    """
    fixture_path = Path(utility_fixture_dir) / "x2mdate.npy"
    if not fixture_path.exists():
        pytest.skip(f"Fixture file not found: {fixture_path}")

    fixture = np.load(fixture_path, allow_pickle=True).item()

    # --- Type 0 (1900 system) date string verification ---
    excel_dates_1900 = fixture["excel_dates_1900"]
    date_strings_1900 = fixture["date_strings_1900"]
    expected_mldates_1900 = fixture["expected_mldates_1900"]
    base_datenum_1900 = fixture["base_datenum_1900"]  # 693960

    result_1900 = x2mdate(excel_dates_1900, date_type=0)

    for i, (ts, expected_str) in enumerate(
        zip(result_1900.flat, date_strings_1900)
    ):
        # Parse date part only (strip time component like ' 06:00')
        expected_date_str = expected_str.split(" ")[0]
        expected_dt = datetime.datetime.strptime(expected_date_str, "%d-%b-%Y")
        assert ts.date() == expected_dt.date(), (
            f"Type 0, index {i}: xldate={excel_dates_1900[i]}, "
            f"expected {expected_date_str}, got {ts.date()}"
        )

    # Verify MATLAB datenum arithmetic consistency:
    # MATLAB datenum = xlsdate + base_datenum_1900
    npt.assert_allclose(
        excel_dates_1900 + base_datenum_1900,
        expected_mldates_1900,
        atol=1e-6,
        rtol=1e-4,
        err_msg="Type 0 MATLAB datenum arithmetic consistency failure",
    )

    # --- Type 1 (1904 system) date string verification ---
    excel_dates_1904 = fixture["excel_dates_1904"]
    date_strings_1904 = fixture["date_strings_1904"]
    expected_mldates_1904 = fixture["expected_mldates_1904"]
    base_datenum_1904 = fixture["base_datenum_1904"]  # 695422

    result_1904 = x2mdate(excel_dates_1904, date_type=1)

    for i, (ts, expected_str) in enumerate(
        zip(result_1904.flat, date_strings_1904)
    ):
        expected_date_str = expected_str.split(" ")[0]
        expected_dt = datetime.datetime.strptime(expected_date_str, "%d-%b-%Y")
        assert ts.date() == expected_dt.date(), (
            f"Type 1, index {i}: xldate={excel_dates_1904[i]}, "
            f"expected {expected_date_str}, got {ts.date()}"
        )

    # Verify MATLAB datenum arithmetic consistency
    npt.assert_allclose(
        excel_dates_1904 + base_datenum_1904,
        expected_mldates_1904,
        atol=1e-6,
        rtol=1e-4,
        err_msg="Type 1 MATLAB datenum arithmetic consistency failure",
    )

    # --- Mixed type vector test ---
    mixed = fixture["mixed_type_test"]
    mixed_dates = mixed["excel_dates"]
    mixed_types = mixed["types"].astype(int)
    mixed_expected_mldates = mixed["expected_mldates"]

    mixed_result = x2mdate(mixed_dates, date_type=mixed_types)

    # Verify shape matches
    assert mixed_result.shape == mixed_dates.shape, (
        f"Mixed test shape: expected {mixed_dates.shape}, "
        f"got {mixed_result.shape}"
    )

    # Verify the per-element type selection works by checking that
    # type=0 entries differ from type=1 entries for the same Excel date.
    # mixed_dates = [35000, 35000, 40000, 40000]
    # mixed_types = [0, 1, 0, 1]
    # So indices 0 and 1 have the same xldate but different types.
    ts_35000_type0 = mixed_result[0]
    ts_35000_type1 = mixed_result[1]
    assert ts_35000_type1 - ts_35000_type0 == pd.Timedelta(days=1462), (
        f"Mixed type test: 35000 type1-type0 offset should be 1462 days, "
        f"got {ts_35000_type1 - ts_35000_type0}"
    )

    ts_40000_type0 = mixed_result[2]
    ts_40000_type1 = mixed_result[3]
    assert ts_40000_type1 - ts_40000_type0 == pd.Timedelta(days=1462), (
        f"Mixed type test: 40000 type1-type0 offset should be 1462 days, "
        f"got {ts_40000_type1 - ts_40000_type0}"
    )

    # --- Default type test from fixture ---
    default_test = fixture["default_type_test"]
    default_dates = default_test["excel_dates"]
    default_expected_mldates = default_test["expected_mldates"]

    default_result = x2mdate(default_dates)

    # Verify docstring example produces expected MATLAB datenums
    npt.assert_allclose(
        default_dates + base_datenum_1900,
        default_expected_mldates,
        atol=1e-6,
        rtol=1e-4,
        err_msg="Default type test MATLAB datenum parity failure",
    )
