def _expected_default_maxlag(T: int, K: int) -> int:
    """Compute the expected default maxlag per covvar.m:39.

    Formula: min(floor(T / K), floor(1.2 * T^(1/3)))
    """
    return int(min(np.floor(T / K), np.floor(1.2 * T ** (1.0 / 3.0))))


