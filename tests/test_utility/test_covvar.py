class TestCovvarMaxlagZero:
    """Edge case: maxlag=0 means no lags, covariance is standard cov."""

    def test_covvar_maxlag_zero(self) -> None:
        """maxlag=0 with any method returns standard covariance."""
        local_rng = np.random.default_rng(555)
        data = local_rng.standard_normal((200, 3))
        V, lags = covvar(data, maxlag=0, method=1)

        # With maxlag=0, lagsused should be empty
        assert len(lags) == 0, f"Expected empty lags for maxlag=0, got {lags}"

        # V should equal population covariance (T-1)/T * cov
        T = data.shape[0]
        expected_cov = np.cov(data, rowvar=False) * ((T - 1) / T)
        npt.assert_allclose(V, expected_cov, atol=1e-10)
