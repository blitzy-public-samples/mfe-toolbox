# 11. test_covvar_iid_data — i.i.d. should select few/no lags
# ---------------------------------------------------------------------------


class TestCovvarIIDData:
    """For i.i.d. data the information criteria should prefer no/few lags."""

    def test_covvar_iid_data(self) -> None:
        """SIC-selected (method=2) lags on large i.i.d. data selects few/no lags.

        With i.i.d. draws, adding lags increases the IC penalty without
        improving fit, so the optimal lag set is typically empty.
        """
        local_rng = np.random.default_rng(9999)
        data = local_rng.standard_normal((500, 3))
        V, lags = covvar(data, maxlag=5, method=2)

        # For large i.i.d. sample, SIC should select 0 lags (empty lags)
        # or at most 1-2 lags by chance. We accept up to 2 as margin.
        assert len(lags) <= 2, (
            f"Expected ≤2 lags for i.i.d. data with SIC, got {len(lags)}: {lags}"
        )

    def test_covvar_iid_aic(self) -> None:
        """AIC-selected (method=3) on i.i.d. data also selects few/no lags."""
        local_rng = np.random.default_rng(8888)
        data = local_rng.standard_normal((500, 3))
        V, lags = covvar(data, maxlag=5, method=3)

        # AIC tends to be more liberal than SIC but still should be small
        assert len(lags) <= 3, (
            f"Expected ≤3 lags for i.i.d. data with AIC, got {len(lags)}: {lags}"
        )


