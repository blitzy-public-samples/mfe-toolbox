class TestCovvarFixtureParity:
    """Numerical parity against MATLAB/Octave reference fixtures.

    Fixtures are loaded from ``tests/fixtures/utility/covvar.npy`` which
    contains 10 test cases generated by Octave 8.4.0 with the original
    ``utility/covvar.m``.

    Per AAP Section 0.7.1: atol=1e-6, rtol=1e-4 are HARD requirements.
    """

    @pytest.mark.parametrize(
        "case_key",
        [
            "test_case_1",
            "test_case_2",
            "test_case_3",
            "test_case_4",
            "test_case_5",
            "test_case_6",
            "test_case_7",
            "test_case_8",
            "test_case_9",
            "test_case_10",
        ],
    )
    def test_covvar_fixture_parity(
        self, fixture_data: dict, case_key: str
    ) -> None:
        """Compare covvar output to MATLAB reference for each fixture case."""
        case = fixture_data[case_key]
        data = case["data"]
        maxlag = case["maxlag"]
        method = case["method"]
        expected_V = case["expected_V"]
        expected_lags = case["expected_lags"]

        # Call the Python implementation
        # maxlag=None in fixture means use default
        if maxlag is None:
            V, lags = covvar(data, method=method)
        else:
            V, lags = covvar(data, maxlag=int(maxlag), method=int(method))

        # Verify covariance matrix parity (atol=1e-6, rtol=1e-4)
        assert_allclose(
            V, expected_V,
            err_msg=(
                f"Covariance matrix mismatch for {case_key} "
                f"(method={method}, maxlag={maxlag})"
            ),
        )

        # Verify lag selection parity
        # expected_lags from MATLAB may be float; convert to int for comparison
        if len(expected_lags) > 0:
            expected_lags_int = np.array(expected_lags, dtype=np.int64)
        else:
            expected_lags_int = np.array([], dtype=np.int64)

        npt.assert_array_equal(
            lags, expected_lags_int,
            err_msg=(
                f"Lag selection mismatch for {case_key}: "
                f"got {lags}, expected {expected_lags_int}"
            ),
        )

    def test_covvar_fixture_covvar_out_properties(
        self, utility_fixture_dir: Path
    ) -> None:
        """Verify the standalone covvar_covvar_out.npy fixture has valid structure.

        This fixture contains a K×K covariance matrix output from covvar().
        Since the input data used to generate this standalone fixture is not
        bundled with the fixture, we verify structural properties: shape,
        symmetry, positive semi-definiteness, and reasonable magnitudes.
        """
        expected_V = load_fixture_npy(utility_fixture_dir, "covvar_covvar_out")

        # Must be a 2-D square matrix
        assert expected_V.ndim == 2, f"Expected 2-D, got {expected_V.ndim}-D"
        K = expected_V.shape[0]
        assert expected_V.shape == (K, K), (
            f"Expected square matrix, got {expected_V.shape}"
        )

        # Must be symmetric (covariance matrices are symmetric)
        npt.assert_allclose(
            expected_V, expected_V.T, atol=1e-12,
            err_msg="covvar_covvar_out fixture is not symmetric",
        )

        # Eigenvalues should be non-negative (positive semi-definite)
        eigenvalues = np.linalg.eigvalsh(expected_V)
        assert np.all(eigenvalues >= -1e-10), (
            f"Fixture covariance has negative eigenvalues: {eigenvalues}"
        )


