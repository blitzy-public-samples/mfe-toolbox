"""
Pytest tests for mfe_toolbox.utility.covvar — VAR-based long-run covariance estimation.

Tests the Python migration of ``utility/covvar.m`` (Den Haan & Levin, 1996).
The ``covvar`` function estimates the long-run covariance matrix of a T×K data
matrix using a VAR-based approach with information criterion-based lag
selection.  Five estimation methods are supported:

    1. Fixed lags 1..maxlag
    2. SIC-selected lag (default)
    3. AIC-selected lag
    4. SIC global search
    5. AIC global search

Every test validates output shapes, symmetry, lag selection behaviour, error
handling, and numerical parity against MATLAB/Octave reference fixtures
(atol=1e-6, rtol=1e-4 per AAP Section 0.7.1).

Fixtures loaded from ``tests/fixtures/utility/covvar.npy`` contain 10 test
cases generated by Octave 8.4.0 using the original ``utility/covvar.m``.
"""

