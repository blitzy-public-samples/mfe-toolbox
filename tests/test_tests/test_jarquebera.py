class TestJarqueberaFullParitySweep:
    """Full parity sweep across all 54 test cases in the main fixture."""

    @pytest.mark.parity
    def test_jarquebera_full_parity_sweep(self, tests_fixture_dir: Path) -> None:
        """Iterate through ALL 54 fixture test cases and verify parity.

        This is the definitive parity test covering all combinations of
        6 datasets × 3 K values × 3 alpha values.
        """
        fixture = load_fixture_npy(tests_fixture_dir, "jarquebera")
        fixture_dict = fixture.item() if fixture.ndim == 0 else fixture

        K_values = fixture_dict["K_values"]
        alpha_values = fixture_dict["alpha_values"]
        dataset_names = fixture_dict["dataset_names"]
        num_K = len(K_values)
        num_alpha = len(alpha_values)
        total_cases = int(fixture_dict["num_test_cases"])

        assert total_cases == 54, f"Expected 54 test cases, got {total_cases}"

        failures: list[str] = []
        case_idx = 0

        for ds_idx, ds_name in enumerate(dataset_names):
            input_data = fixture_dict[str(ds_name)].ravel()

            for k_idx, K in enumerate(K_values):
                for a_idx, alpha in enumerate(alpha_values):
                    expected_stat = float(
                        fixture_dict["statistic"][case_idx, 0]
                    )
                    expected_pval = float(fixture_dict["pval"][case_idx, 0])
                    expected_H = bool(fixture_dict["H"][case_idx, 0])

                    stat, pval, H = jarquebera(
                        input_data, K=int(K), alpha=float(alpha)
                    )

                    try:
                        npt.assert_allclose(
                            stat, expected_stat, atol=ATOL, rtol=RTOL,
                        )
                    except AssertionError:
                        failures.append(
                            f"Case {case_idx} ({ds_name}, K={K}, "
                            f"alpha={alpha}): stat {stat} != {expected_stat}"
                        )

                    try:
                        npt.assert_allclose(
                            pval, expected_pval, atol=ATOL, rtol=RTOL,
                        )
                    except AssertionError:
                        failures.append(
                            f"Case {case_idx} ({ds_name}, K={K}, "
                            f"alpha={alpha}): pval {pval} != {expected_pval}"
                        )

                    if H != expected_H:
                        failures.append(
                            f"Case {case_idx} ({ds_name}, K={K}, "
                            f"alpha={alpha}): H {H} != {expected_H}"
                        )

                    case_idx += 1

        assert case_idx == total_cases, (
            f"Processed {case_idx} cases, expected {total_cases}"
        )
        assert len(failures) == 0, (
            f"{len(failures)} parity failures:\n" + "\n".join(failures)
        )
