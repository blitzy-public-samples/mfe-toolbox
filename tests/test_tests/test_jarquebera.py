class TestJarqueberaReturnTypes:
    """Return type and invariant tests."""

    def test_jarquebera_return_types(self, rng: np.random.Generator) -> None:
        """Statistic is float, pval is float, H is bool.

        Ref: jarquebera.py signature → tuple[float, float, bool]
        """
        data = rng.standard_normal(100)
        statistic, pval, H = jarquebera(data)

        assert isinstance(statistic, (float, np.floating)), (
            f"statistic type is {type(statistic)}, expected float"
        )
        assert isinstance(pval, (float, np.floating)), (
            f"pval type is {type(pval)}, expected float"
        )
        assert isinstance(H, bool), (
            f"H type is {type(H)}, expected bool"
        )

    def test_jarquebera_stat_nonnegative(self, rng: np.random.Generator) -> None:
        """JB statistic must be non-negative (squared terms only).

        Ref: jarquebera.m:71 — (T-K) * (skew^2/6 + kurt^2/24)
        All terms are squared → statistic ≥ 0 always.
        """
        # Test with various data patterns
        for seed in [0, 42, 99, 777]:
            local_rng = np.random.default_rng(seed)
            data = local_rng.standard_normal(200)
            statistic, _, _ = jarquebera(data)
            assert statistic >= 0.0, (
                f"Negative JB statistic ({statistic}) with seed={seed}"
            )

    def test_jarquebera_pval_range(self, rng: np.random.Generator) -> None:
        """P-value must be in [0, 1].

        Ref: jarquebera.m:72 — pval = 1 - chi2cdf(statistic, 2)
        Since chi2.cdf returns values in [0, 1], pval ∈ [0, 1].
        """
        for seed in [0, 42, 99, 777]:
            local_rng = np.random.default_rng(seed)
            data = local_rng.standard_normal(200)
            _, pval, _ = jarquebera(data)
            assert 0.0 <= pval <= 1.0, (
                f"P-value ({pval}) outside [0, 1] with seed={seed}"
            )

    def test_jarquebera_chi2_2df(self, rng: np.random.Generator) -> None:
        """Verify chi-squared with 2 degrees of freedom is used for p-value.

        Ref: jarquebera.m:72 — ``pval = 1 - chi2cdf(statistic, 2)``
        Independently compute p-value using scipy.stats.chi2 to confirm.
        """
        data = rng.standard_normal(300)
        statistic, pval, _ = jarquebera(data)

        # Independent p-value calculation using chi2.sf (survival function)
        # chi2.sf(x, df) = 1 - chi2.cdf(x, df)
        expected_pval = float(chi2.sf(statistic, 2))

        npt.assert_allclose(
            pval, expected_pval, atol=ATOL, rtol=RTOL,
            err_msg="p-value does not match chi2(df=2) survival function",
        )

        # Also verify via the CDF formulation explicitly
        expected_pval_cdf = float(1.0 - chi2.cdf(statistic, 2))
        npt.assert_allclose(
            pval, expected_pval_cdf, atol=ATOL, rtol=RTOL,
            err_msg="p-value does not match 1 - chi2.cdf(stat, 2)",
        )


