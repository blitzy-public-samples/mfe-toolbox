class TestJarqueberaParityNormal:
    """Compare against MATLAB fixture for normal data (test_jarquebera_parity_normal)."""

    @pytest.mark.parity
    def test_jarquebera_parity_normal(self, tests_fixture_dir: Path) -> None:
        """Verify numerical parity for normal data against MATLAB/Octave fixtures.

        Loads the ``jarquebera.npy`` fixture containing 54 test cases across
        6 datasets, 3 K values, and 3 alpha values. Tests the 3 normal
        datasets (normal_100, normal_500, normal_1000).
        """
        fixture = load_fixture_npy(tests_fixture_dir, "jarquebera")
        fixture_dict = fixture.item() if fixture.ndim == 0 else fixture

        K_values = fixture_dict["K_values"]  # [0, 2, 5]
        alpha_values = fixture_dict["alpha_values"]  # [0.01, 0.05, 0.10]

        # Test normal datasets (first 3 of 6)
