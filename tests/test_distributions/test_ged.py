"""Comprehensive pytest tests for the Generalized Error Distribution (GED) functions.

Tests all 5 GED distribution modules from ``mfe_toolbox.distributions``:
    - gedcdf   — CDF of the GED
    - gedinv   — Inverse CDF (quantile function) of the GED
    - gedloglik — Log-likelihood of the GED
    - gedpdf   — PDF of the GED
    - gedrnd   — Random variate generation from the GED

Per AAP Section 0.7.1:
    - Numerical parity: numpy.testing.assert_allclose(actual, expected, atol=1e-6, rtol=1e-4)
    - Test scalar, vector, and matrix inputs
    - Coverage threshold: >=90% line coverage
    - All tests MUST pass with ``pytest -x --tb=short``
    - GED shape parameter for primary tests: v=1.5
    - Invalid inputs must raise equivalent exceptions

References
----------
.. [1] Tadikamalla (1980), J.Am.Stat.Assoc. (75)
.. [2] Nelson (1991), Econometrica
"""

