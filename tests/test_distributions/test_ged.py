class TestGedCdf:
    """Unit, property, and parity tests for the GED cumulative distribution function."""

    def test_gedcdf_scalar_zero(self, ged_v):
        """CDF at x=0 should be 0.5 (symmetry of GED)."""
        result = gedcdf(np.array([0.0]), np.array([ged_v]))
        npt.assert_allclose(result, 0.5, atol=ATOL,
                            err_msg="CDF(0) must be 0.5 for symmetric GED")

    def test_gedcdf_vector_monotonic(self, ged_v):
        """CDF should be monotonically non-decreasing over a sorted x vector."""
        x = np.linspace(-4, 4, 50)
        v = np.full_like(x, ged_v)
        p = gedcdf(x, v)
        diffs = np.diff(p)
        assert np.all(diffs >= -1e-12), "CDF must be monotonically non-decreasing"

    def test_gedcdf_bounds(self, ged_v):
        """CDF values should be in [0, 1] for all x."""
        x = np.linspace(-10, 10, 100)
        v = np.full_like(x, ged_v)
        p = gedcdf(x, v)
        assert np.all(p >= 0.0), "CDF must be >= 0"
        assert np.all(p <= 1.0), "CDF must be <= 1"

    def test_gedcdf_symmetry(self, ged_v):
        """gedcdf(x, v) + gedcdf(-x, v) ≈ 1.0 for symmetric GED."""
        x = np.array([0.5, 1.0, 1.5, 2.0, 3.0])
        v = np.full_like(x, ged_v)
        p_pos = gedcdf(x, v)
        p_neg = gedcdf(-x, v)
        npt.assert_allclose(p_pos + p_neg, 1.0, atol=ATOL,
                            err_msg="CDF symmetry: CDF(x) + CDF(-x) must ≈ 1")

    def test_gedcdf_nan_for_invalid_v(self):
        """v < 1 should produce NaN."""
        x = np.array([0.0, 1.0, -1.0])
        v = np.full_like(x, 0.5)
        result = gedcdf(x, v)
