class TestGedPdf:
    """Unit, property, and parity tests for the GED probability density function."""

    def test_gedpdf_scalar_v(self, ged_v):
        """Scalar x and scalar v=1.5 should produce a non-negative, finite PDF."""
        x = np.array([0.5])
        v = np.array([ged_v])
        result = gedpdf(x, v)
        assert result.shape == (1,), f"Expected shape (1,), got {result.shape}"
        assert np.all(result >= 0), "PDF must be non-negative"
        assert np.all(np.isfinite(result)), "PDF must be finite for valid inputs"

    def test_gedpdf_vector_input(self, ged_v):
        """Vector x=[-2,-1,0,1,2] with v=1.5; all values >= 0 and finite."""
        x = X_VECTOR.copy()
        v = np.full_like(x, ged_v)
        result = gedpdf(x, v)
        assert result.shape == x.shape, f"Shape mismatch: {result.shape} vs {x.shape}"
        assert np.all(result >= 0), "PDF must be non-negative for all x"
        assert np.all(np.isfinite(result)), "PDF must be finite for valid inputs"

    def test_gedpdf_symmetry(self, ged_v):
        """GED is symmetric: gedpdf(x, v) == gedpdf(-x, v) for all x."""
        x = np.array([0.5, 1.0, 1.5, 2.0, 3.0])
        v = np.full_like(x, ged_v)
        f_pos = gedpdf(x, v)
        f_neg = gedpdf(-x, v)
        npt.assert_allclose(f_pos, f_neg, atol=ATOL, rtol=RTOL,
                            err_msg="GED PDF must be symmetric about zero")

    def test_gedpdf_v_equals_2_is_normal(self):
        """When v=2, GED PDF should match standard normal PDF exactly.

        Ref: Tadikamalla (1980) — GED with v=2 reduces to N(0,1).
        """
        x = np.linspace(-3, 3, 50)
        v = np.full_like(x, 2.0)
        f_ged = gedpdf(x, v)
        f_norm = norm.pdf(x)
        npt.assert_allclose(f_ged, f_norm, atol=1e-10, rtol=1e-10,
                            err_msg="GED(v=2) must match standard normal PDF")

    def test_gedpdf_nan_for_invalid_v(self):
        """v < 1 should produce NaN output."""
        x = np.array([0.0, 1.0, -1.0])
        v = np.full_like(x, 0.5)
        result = gedpdf(x, v)
        assert np.all(np.isnan(result)), "v<1 must produce NaN for all elements"

    def test_gedpdf_integrates_to_one(self, ged_v):
        """Numerical integration of gedpdf over [-10, 10] should ≈ 1.0."""
        integral, _ = quad(
            lambda t: float(gedpdf(np.array([t]), np.array([ged_v]))[0]),
            -10.0, 10.0
        )
        npt.assert_allclose(integral, 1.0, atol=1e-6,
                            err_msg="GED PDF must integrate to 1.0")

    def test_gedpdf_integrates_to_one_v2(self):
        """Integration of gedpdf with v=2 (normal) over wide range."""
        integral, _ = quad(
            lambda t: float(gedpdf(np.array([t]), np.array([2.0]))[0]),
            -10.0, 10.0
        )
        npt.assert_allclose(integral, 1.0, atol=1e-10,
                            err_msg="GED(v=2) PDF must integrate to 1.0")

    def test_gedpdf_integrates_to_one_v1(self):
        """Integration of gedpdf with v=1 (Laplace) over wide range."""
        integral, _ = quad(
            lambda t: float(gedpdf(np.array([t]), np.array([1.0]))[0]),
            -15.0, 15.0
        )
        npt.assert_allclose(integral, 1.0, atol=1e-6,
                            err_msg="GED(v=1) PDF must integrate to 1.0")

    def test_gedpdf_non_negative_dense_grid(self, ged_v):
        """PDF >= 0 across a dense grid of 200 points."""
        x = np.linspace(-5, 5, 200)
        v = np.full_like(x, ged_v)
        result = gedpdf(x, v)
        assert np.all(result >= 0), "PDF must be non-negative everywhere"

    def test_gedpdf_peak_at_zero(self, ged_v):
        """PDF should attain its maximum at x=0 for symmetric GED."""
        x = np.array([-2.0, -1.0, -0.5, 0.0, 0.5, 1.0, 2.0])
        v = np.full_like(x, ged_v)
        f = gedpdf(x, v)
        # Index 3 is x=0
        assert f[3] >= f[0], "PDF at 0 must be >= PDF at -2"
        assert f[3] >= f[1], "PDF at 0 must be >= PDF at -1"
        assert f[3] >= f[4], "PDF at 0 must be >= PDF at 0.5"
        assert f[3] >= f[6], "PDF at 0 must be >= PDF at 2"

    def test_gedpdf_scalar_input(self):
        """Scalar x=0.0, v=2.0 should produce result matching 1/sqrt(2*pi)."""
        result = gedpdf(0.0, 2.0)
        expected = 1.0 / np.sqrt(2.0 * np.pi)
        npt.assert_allclose(np.asarray(result).flat[0], expected, atol=1e-10)

    def test_gedpdf_tail_decay(self, ged_v):
        """PDF should decrease as |x| increases from the mode."""
        x_abs = np.array([0.0, 0.5, 1.0, 2.0, 3.0, 5.0])
        v = np.full_like(x_abs, ged_v)
        f = gedpdf(x_abs, v)
        # Each successive value should be <= the previous
        for i in range(1, len(f)):
            assert f[i] <= f[i - 1] + 1e-15, \
                f"PDF should decay in the tail: f({x_abs[i]})={f[i]} > f({x_abs[i-1]})={f[i-1]}"

