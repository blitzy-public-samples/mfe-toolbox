class TestGedIntegration:
    """Cross-function integration tests for GED distribution consistency."""

    def test_cdf_pdf_consistency(self, ged_v):
        """Numerical derivative of CDF ≈ PDF (central finite difference).

        dCDF/dx ≈ (CDF(x+h) - CDF(x-h)) / (2h) should match PDF(x).
        """
        h = 1e-5
        x_test = np.array([-1.5, -0.5, 0.0, 0.5, 1.5])
        for xi in x_test:
            cdf_plus = gedcdf(np.array([xi + h]), np.array([ged_v]))[0]
            cdf_minus = gedcdf(np.array([xi - h]), np.array([ged_v]))[0]
            numerical_pdf = (cdf_plus - cdf_minus) / (2.0 * h)
            analytical_pdf = gedpdf(np.array([xi]), np.array([ged_v]))[0]
            npt.assert_allclose(
                numerical_pdf, analytical_pdf, atol=1e-4, rtol=1e-3,
                err_msg=f"CDF derivative must ≈ PDF at x={xi}"
            )

    def test_cdf_inv_roundtrip(self, ged_v):
        """gedcdf(gedinv(p, v), v) ≈ p for p in (0.01, 0.99)."""
        p_test = np.array([0.01, 0.05, 0.1, 0.25, 0.5, 0.75, 0.9, 0.95, 0.99])
        v = np.full_like(p_test, ged_v)
        x_inv = gedinv(p_test, v)
        p_recovered = gedcdf(x_inv, v)
        npt.assert_allclose(p_recovered, p_test, atol=1e-5, rtol=1e-4,
                            err_msg="CDF(INV(p)) must recover p")

    def test_inv_cdf_roundtrip(self, ged_v):
        """gedinv(gedcdf(x, v), v) ≈ x for moderate x values."""
        x_test = np.array([-2.0, -1.0, -0.5, 0.0, 0.5, 1.0, 2.0])
        v = np.full_like(x_test, ged_v)
        p = gedcdf(x_test, v)
        x_recovered = gedinv(p, v)
        npt.assert_allclose(x_recovered, x_test, atol=1e-5, rtol=1e-4,
                            err_msg="INV(CDF(x)) must recover x")

    def test_loglik_pdf_consistency(self, ged_v):
        """exp(lls[i]) ≈ gedpdf(z[i], v) / sqrt(sigma2[i]).

        The log-likelihood at observation i for the GED(mu, sigma2, v) is:
            lls[i] = log(gedpdf(z[i], v) / sqrt(sigma2[i]))
        where z[i] = (x[i] - mu) / sqrt(sigma2[i]).
        """
        rng_local = np.random.default_rng(42)
        x = rng_local.standard_normal(20)
        sigma2 = np.ones(20)
        mu = 0.0
        _, lls = gedloglik(x, mu, sigma2, ged_v)
        z = (x - mu) / np.sqrt(sigma2)
        for i in range(len(x)):
            pdf_val = gedpdf(np.array([z[i]]), np.array([ged_v]))[0]
            expected_ll = np.log(pdf_val / np.sqrt(sigma2[i]))
            npt.assert_allclose(
                lls[i], expected_ll, atol=1e-6, rtol=1e-4,
                err_msg=f"loglik-PDF consistency failed at i={i}"
            )

    def test_loglik_pdf_consistency_varying_sigma(self, ged_v):
        """loglik-PDF consistency with varying sigma2 values."""
        rng_local = np.random.default_rng(99)
        x = rng_local.standard_normal(15)
        sigma2 = 0.5 + rng_local.random(15) * 2.0  # sigma2 in [0.5, 2.5]
        mu = 0.0
        _, lls = gedloglik(x, mu, sigma2, ged_v)
        z = (x - mu) / np.sqrt(sigma2)
        for i in range(len(x)):
            pdf_val = gedpdf(np.array([z[i]]), np.array([ged_v]))[0]
            expected_ll = np.log(pdf_val / np.sqrt(sigma2[i]))
            npt.assert_allclose(
                lls[i], expected_ll, atol=1e-5, rtol=1e-3,
                err_msg=f"loglik-PDF consistency (varying sigma) failed at i={i}"
            )

    def test_multiple_v_values_consistency(self):
        """Test CDF/PDF/INV consistency across multiple v values: 1.0, 1.5, 2.0, 3.0."""
        for v_val in [1.0, 1.5, 2.0, 3.0]:
            x = np.linspace(-3, 3, 20)
            v = np.full_like(x, v_val)

            # gedpdf: non-negative
            f = gedpdf(x, v)
            assert np.all(f >= 0), f"gedpdf must be >= 0 for v={v_val}"

            # gedcdf: in [0, 1]
            p = gedcdf(x, v)
            assert np.all(p >= 0) and np.all(p <= 1), \
                f"gedcdf must be in [0,1] for v={v_val}"

            # gedcdf monotonic
            assert np.all(np.diff(p) >= -1e-10), \
                f"gedcdf must be non-decreasing for v={v_val}"

            # gedinv roundtrip
            p_test = np.array([0.1, 0.5, 0.9])
            v_test = np.full_like(p_test, v_val)
            x_inv = gedinv(p_test, v_test)
            p_rec = gedcdf(x_inv, v_test)
            npt.assert_allclose(p_rec, p_test, atol=1e-4, rtol=1e-3,
                                err_msg=f"CDF-INV roundtrip failed for v={v_val}")

    def test_random_variates_cdf_uniformity(self, ged_v):
        """CDF of GED random variates should be approximately uniform on [0,1]."""
        rng_local = np.random.default_rng(42)
        r = gedrnd(ged_v, 5000, rng=rng_local)
        v = np.full_like(r, ged_v)
        u = gedcdf(r, v)
        # U should be approximately Uniform(0,1): mean ≈ 0.5, var ≈ 1/12
        npt.assert_allclose(np.mean(u), 0.5, atol=0.05,
                            err_msg="CDF(GED samples) mean should be ~0.5")
        npt.assert_allclose(np.var(u), 1.0 / 12.0, atol=0.02,
                            err_msg="CDF(GED samples) variance should be ~1/12")
