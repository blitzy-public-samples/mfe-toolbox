# ---------------------------------------------------------------------------
# Fixture loading helper
# ---------------------------------------------------------------------------
def _load_ged_fixture(fixture_dir, name):
    """Load a GED fixture .npy file and extract the dict from 0-D object array.

    The fixture .npy files generated by convert_fixtures.py are stored as
    0-dimensional object arrays wrapping a dict. This helper extracts the
    dict via ``.item()`` for convenient key-based access.

    Parameters
    ----------
    fixture_dir : pathlib.Path
        Path to the distributions fixture directory.
    name : str
        Base name of the fixture file (without .npy extension).

    Returns
    -------
    dict
        Dictionary of fixture data arrays and metadata.
    """
    raw = load_fixture_npy(fixture_dir, name)
    # Handle 0-D object array (dict wrapped in ndarray)
    if raw.ndim == 0 and raw.dtype == object:
        return raw.item()
    return raw


