@pytest.fixture(scope="session")
def univariate_data() -> np.ndarray:
    """Generate standardised test return data for univariate GARCH estimation.

    Creates a T = 1000 return series using ``numpy.random.default_rng(42)``
    that is:

    * Scaled by 0.01 to resemble daily financial returns
      (mean ≈ 0, std ≈ 0.01–0.02).
    * Demeaned so the mean-zero assumption required by all GARCH model
      families is satisfied.

    The deterministic seed guarantees reproducible test data across runs
    and platforms, matching the MATLAB fixture generation script
    (``rng(42, 'twister')``).

    Returns
    -------
    np.ndarray
        Shape ``(1000,)`` mean-zero return series scaled to daily-return
        magnitude.
    """
    rng: np.random.Generator = np.random.default_rng(42)
    returns: np.ndarray = rng.standard_normal(1000) * 0.01
    # Demean to satisfy GARCH mean-zero assumption
    # Ref: generate_fixtures.m — epsilon = epsilon - mean(epsilon)
    returns = returns - returns.mean()
    return returns


