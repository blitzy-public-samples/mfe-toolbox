def load_univariate_fixture(
    fixture_dir: Path,
    model_name: str,
    fixture_name: str,
) -> np.ndarray:
    """Load a specific ``.npy`` fixture file for a univariate GARCH model.

    Constructs the path ``fixture_dir / model_name / fixture_name.npy``
    and loads the array.  If the file does not exist the calling test is
    gracefully skipped via ``pytest.skip``.

    Parameters
    ----------
    fixture_dir : Path
        Path to the univariate fixtures directory
        (``tests/fixtures/univariate``).
    model_name : str
        Model subdirectory name, e.g. ``'agarch'``, ``'tarch'``,
        ``'egarch'``.
    fixture_name : str
        Fixture file base name (without ``.npy`` extension), e.g.
        ``'parameters'``, ``'ht'``, ``'loglikelihood'``.

    Returns
    -------
    np.ndarray
        Array loaded from the fixture file.

    Raises
    ------
    pytest.skip
        When the requested fixture file is not found on disk.
    """
    path: Path = fixture_dir / model_name / f"{fixture_name}.npy"
    if not path.exists():
        pytest.skip(f"Fixture {path} not found")
    # allow_pickle=True for object-dtype arrays containing dicts of test
    # cases generated by convert_fixtures.py.  These files are committed to
    # the repository and are NOT user-supplied.
    return np.load(path, allow_pickle=True)


def load_univariate_input(
    fixture_dir: Path,
    model_name: str,
) -> np.ndarray:
    """Load input data used for MATLAB reference estimation.

    Looks for ``fixture_dir / model_name / input_data.npy`` — the return
    series that was fed into the MATLAB estimator when generating the
    reference fixtures.

    Parameters
    ----------
    fixture_dir : Path
        Path to the univariate fixtures directory
        (``tests/fixtures/univariate``).
    model_name : str
        Model subdirectory name, e.g. ``'agarch'``, ``'tarch'``.

    Returns
    -------
    np.ndarray
        Input data array used for MATLAB reference estimation.

    Raises
    ------
    pytest.skip
        When the input data fixture is not found on disk.
    """
    path: Path = fixture_dir / model_name / "input_data.npy"
    if not path.exists():
        pytest.skip(f"Input fixture {path} not found")
    return np.load(path, allow_pickle=True)
