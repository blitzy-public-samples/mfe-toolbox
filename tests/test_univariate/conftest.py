"""Shared fixtures and configuration for univariate GARCH model tests.

Supplements the top-level ``tests/conftest.py`` which provides:
- ATOL = 1e-6 and RTOL = 1e-4 tolerance constants
- ``fixture_dir`` — root fixture directory resolver (supports MFE_FIXTURE_DIR)
- ``load_fixture_npy()`` / ``load_fixture_csv()`` — generic fixture loading
- ``assert_allclose()`` — convenience wrapper for numerical parity checks
- ``rng`` — ``numpy.random.default_rng(42)`` shared random generator

This file provides **univariate-specific** fixtures and helpers:

Fixtures:
    univariate_fixture_dir : Path
        Path to ``tests/fixtures/univariate/`` directory (session-scoped).
        Skips all tests if directory does not exist.
    univariate_data : np.ndarray
        Standard T=1000 return series, demeaned, scaled ~N(0, 0.01²)
        (session-scoped).
    univariate_data_short : np.ndarray
        Short T=200 return series for quick tests (session-scoped).
    heavy_bivariate_data : np.ndarray
        T×2 bivariate data for HEAVY model tests (session-scoped).
    default_garch_params : np.ndarray
        Default GARCH(1,1) parameter vector [omega, alpha, beta].
    default_tarch_params : np.ndarray
        Default TARCH(1,1,1) parameter vector [omega, alpha, gamma, beta].
    default_agarch_params : np.ndarray
        Default AGARCH(1,1) parameter vector [omega, alpha, gamma, beta].
    default_egarch_params : np.ndarray
        Default EGARCH(1,1,1) parameter vector [omega, alpha, gamma, beta].
    default_figarch_params : np.ndarray
        Default FIGARCH(1,d,1) parameter vector [omega, phi, d, beta].
    default_igarch_params : np.ndarray
        Default IGARCH(1,1) parameter vector [omega, alpha].
    default_aparch_params : np.ndarray
        Default APARCH(1,1,1) parameter vector
        [omega, alpha, gamma, beta, delta].

Helper Functions:
    load_univariate_fixture(fixture_dir, model_name, fixture_name)
        Load a model-specific .npy fixture from the univariate fixtures dir.
    load_univariate_input(fixture_dir, model_name)
        Load the input data .npy fixture used for MATLAB reference estimation.

Custom Markers:
    parity
        Marks tests requiring MATLAB fixture comparison.
    requires_fixtures
        Marks tests that need fixture files generated by
        ``scripts/generate_fixtures.m``.
    slow
        Marks tests that may take >5 seconds (deselect with
        ``-m 'not slow'``).
"""

from __future__ import annotations

