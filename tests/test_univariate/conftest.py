@pytest.fixture(scope="session")
def heavy_bivariate_data() -> np.ndarray:
    """Generate T × K = 2 bivariate data for HEAVY model tests.

    The HEAVY (High-frEquency-bAsed VolatilitY) model of Shephard and
    Sheppard requires a T × K matrix where each column represents a
    different observable.  The standard bivariate specification uses:

    * **Column 0** — Squared returns (return variance proxy).
    * **Column 1** — Realized measure proxy (absolute returns scaled by
      uniform noise in [0.8, 1.2]).

    Both columns are guaranteed non-negative, satisfying the HEAVY model's
    positivity requirements.

    Returns
    -------
    np.ndarray
        Shape ``(500, 2)`` non-negative bivariate data matrix.
    """
    rng: np.random.Generator = np.random.default_rng(42)
    T: int = 500
    returns: np.ndarray = rng.standard_normal(T) * 0.01
    # Realized measure proxy: |returns| × uniform noise ∈ [0.8, 1.2]
    realized: np.ndarray = np.abs(returns) * rng.uniform(0.8, 1.2, T)
    data: np.ndarray = np.column_stack([returns ** 2, realized])
    return data


