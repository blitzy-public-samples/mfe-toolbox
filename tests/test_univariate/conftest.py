@pytest.fixture(scope="session")
def univariate_fixture_dir(fixture_dir: Path) -> Path:
    """Path to ``tests/fixtures/univariate/`` directory.

    Resolves the fixture directory containing MATLAB reference outputs for
    all 7 GARCH model families (AGARCH, APARCH, EGARCH, FIGARCH, HEAVY,
    IGARCH, TARCH).  Uses the ``fixture_dir`` fixture from the parent
    ``tests/conftest.py``.

    If the directory does not exist the entire test collection scoped under
    this fixture is skipped gracefully, allowing the test suite to degrade
    cleanly before fixtures have been generated.

    Parameters
    ----------
    fixture_dir : Path
        Base fixture directory from parent conftest.

    Returns
    -------
    Path
        ``fixture_dir / "univariate"`` if it exists.

    Raises
    ------
    pytest.skip
        When the univariate fixtures directory is not found on disk.
    """
    path: Path = fixture_dir / "univariate"
    if not path.exists():
        pytest.skip(
            "Univariate fixtures not found; "
            "run scripts/generate_fixtures.m first"
        )
    return path


