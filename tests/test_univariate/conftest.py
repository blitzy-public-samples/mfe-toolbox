# ---------------------------------------------------------------------------
# Pytest Configuration Hook — Custom Marker Registration
# ---------------------------------------------------------------------------

def pytest_configure(config: Any) -> None:
    """Register custom markers for univariate GARCH model tests.

    Markers registered here supplement those from the parent
    ``tests/conftest.py``.  Duplicate registrations are harmless — pytest
    silently deduplicates.

    Markers
    -------
    parity
        Marks tests that compare Python outputs against MATLAB reference
        fixture files using ``numpy.testing.assert_allclose`` with
        ``atol=1e-6, rtol=1e-4``.
    requires_fixtures
        Marks tests that require generated fixture files from
        ``scripts/generate_fixtures.m`` + ``scripts/convert_fixtures.py``.
    slow
        Marks tests that may take >5 seconds to execute (deselect with
        ``-m 'not slow'``).
    """
    config.addinivalue_line(
        "markers",
        "parity: marks tests requiring MATLAB fixture comparison",
    )
    config.addinivalue_line(
        "markers",
        "requires_fixtures: marks tests that need fixture files",
    )
    config.addinivalue_line(
        "markers",
        "slow: marks tests that may take >5 seconds "
        "(deselect with -m 'not slow')",
    )


