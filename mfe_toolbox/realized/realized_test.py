    # ==================================================================
    # Phase 1: Load data
    # Ref: realized_test.m:1-3 — load ES_20090817; price=trades.price; time=trades.time
    # ==================================================================
    print("Loading ES_20090817 data...")
    price, time = _load_es_data()
    print(f"  Loaded {len(price)} trade observations.")

    # ==================================================================
    # Phase 2: Set up time parameters
    # Ref: realized_test.m:4-8
    # ==================================================================
    # Ref: realized_test.m:4 — timeType='wall'
    time_type: str = 'wall'

    # Ref: realized_test.m:5 — fixedInterval = seconds2wall(wall2seconds(83000):300:wall2seconds(150000))
    # MATLAB colon operator start:step:end is inclusive; Python np.arange end is exclusive
    # so we add 1 to the stop value to make it inclusive.
    ws_start = wall2seconds(np.array([83000.0]))[0]   # 29800.0 (8:30 AM)
    ws_stop = wall2seconds(np.array([150000.0]))[0]    # 54000.0 (3:00 PM)
    fixed_interval = seconds2wall(
        np.arange(ws_start, ws_stop + 1, 300.0)
    )

