def _resolve_fixture_dir() -> str:
    """Resolve the directory containing ES_20090817 fixture data.

    Checks the optional ``MFE_FIXTURE_DIR`` environment variable first
    (per AAP §0.7.2), then falls back to the default test fixtures
    location relative to the repository root.

    Returns
    -------
    str
        Absolute path to the fixture directory.
    """
    # Ref: AAP §0.7.2 — optional MFE_FIXTURE_DIR override for CI
    env_dir = os.environ.get("MFE_FIXTURE_DIR")
    if env_dir is not None:
        candidate = os.path.join(env_dir, "realized")
        if os.path.exists(candidate):
            return candidate
        # Also check if env_dir already points to the realized subdir
        if os.path.exists(env_dir):
            return env_dir

    # Default: tests/fixtures/realized relative to project root
    # Walk up from this module's location to the repo root
    module_dir = os.path.dirname(os.path.abspath(__file__))  # mfe_toolbox/realized/
    package_root = os.path.dirname(module_dir)                # mfe_toolbox/
    repo_root = os.path.dirname(package_root)                 # project root
    return os.path.join(repo_root, "tests", "fixtures", "realized")


def _load_es_data() -> tuple[np.ndarray, np.ndarray]:
    """Load ES_20090817 trade price and time arrays from fixture files.

    Attempts multiple loading strategies:
    1. Separate .npy files for price and time (preferred)
    2. Combined .npy file (legacy)
    3. scipy.io.loadmat fallback for .mat format

    Returns
    -------
    price : np.ndarray
        1-D array of trade prices.
    time : np.ndarray
        1-D array of trade times in wall-clock (HHMMSS) format.

    Raises
    ------
    FileNotFoundError
        If no suitable data file is found.
    """
    fixture_dir = _resolve_fixture_dir()

    # Strategy 1: Separate .npy files (generated by convert_fixtures.py)
    price_path = os.path.join(fixture_dir, "ES_20090817_trades_price.npy")
    time_path = os.path.join(fixture_dir, "ES_20090817_trades_time.npy")
    if os.path.exists(price_path) and os.path.exists(time_path):
        price = np.load(price_path).ravel().astype(np.float64)
        time_arr = np.load(time_path).ravel().astype(np.float64)
        return price, time_arr

    # Strategy 2: Combined .npy file (allow_pickle for structured arrays)
    combined_path = os.path.join(fixture_dir, "ES_20090817.npy")
    if os.path.exists(combined_path):
        try:
            data = np.load(combined_path, allow_pickle=True)
            # May be a structured array or dict-like object
            if hasattr(data, 'item'):
                data = data.item()
            if isinstance(data, dict):
                # Extract trades.price and trades.time
                trades = data.get("trades", data)
                if isinstance(trades, dict):
                    price = np.asarray(trades["price"], dtype=np.float64).ravel()
                    time_arr = np.asarray(trades["time"], dtype=np.float64).ravel()
                    return price, time_arr
        except Exception:
            pass  # Fall through to scipy fallback

    # Strategy 3: scipy.io.loadmat fallback
    # Ref: realized_test.m:1 — load ES_20090817
    mat_path = os.path.join(fixture_dir, "ES_20090817.mat")
    if os.path.exists(mat_path):
        try:
            from scipy.io import loadmat
            mat_data = loadmat(mat_path)
            # MATLAB struct: trades.price, trades.time
            if "trades" in mat_data:
                trades = mat_data["trades"]
                price = np.asarray(
                    trades["price"][0, 0], dtype=np.float64
                ).ravel()
                time_arr = np.asarray(
                    trades["time"][0, 0], dtype=np.float64
                ).ravel()
                return price, time_arr
            # Flat variables in .mat
            if "price" in mat_data and "time" in mat_data:
                price = np.asarray(mat_data["price"], dtype=np.float64).ravel()
                time_arr = np.asarray(mat_data["time"], dtype=np.float64).ravel()
                return price, time_arr
        except ImportError:
            pass  # scipy not available

    raise FileNotFoundError(
        f"Could not locate ES_20090817 data in '{fixture_dir}'. "
        "Ensure fixture files have been generated via "
        "'python scripts/convert_fixtures.py'."
    )


